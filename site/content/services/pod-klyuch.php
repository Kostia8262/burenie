<p>
  «Под ключ» означает, что вы один раз договариваетесь о цене и дальше не
  ищете отдельно бурильщиков, отдельно монтажников и отдельно электрика.
  Мы приходим на участок без воды, а уходим, когда из крана в доме идёт вода
  с рабочим напором.
</p>

<h2>Что входит в работу</h2>
<ul>
  <li>выезд инженера, осмотр участка и расчёт сметы;</li>
  <li>бурение до рабочего водоносного горизонта;</li>
  <li>обсадная колонна с фильтром, подобранная под грунт и под насос;</li>
  <li>прокачка скважины до чистой воды;</li>
  <li>обустройство — летний вариант, адаптер или кессон;</li>
  <li>подбор и монтаж насоса, гидроаккумулятор, автоматика;</li>
  <li>траншея и ввод трубы в дом ниже глубины промерзания;</li>
  <li>пусконаладка и проверка под нагрузкой;</li>
  <li>паспорт скважины и гарантия.</li>
</ul>

<h2>Сколько это занимает</h2>
<p>
  Само бурение — один-два дня. Обустройство и ввод в дом добавляют ещё один-два,
  в зависимости от расстояния до дома и от того, нужно ли копать траншею по
  мёрзлому грунту. То есть от звонка до воды обычно проходит меньше недели,
  и большая часть этого времени — ожидание своей очереди, а не работа.
</p>

<h2>Из чего складывается цена</h2>
<p>
  Основные факторы — глубина, диаметр обсадной трубы, грунт на участке и
  выбранный вариант обустройства. Подробно мы разобрали это на
  <a href="<?= e(u('/ceny/')) ?>">странице о ценах</a>. Проходка стоит от <?= e(number_format(PRICE_DRILL_FROM, 0, ',', ' ')) ?> ₽
  за метр, остальное считается отдельно — там же написано, что входит в эту
  цифру и что стоит проверять в чужих коммерческих предложениях.
</p>

<h2>Что остаётся у вас на руках</h2>
<p>
  Паспорт скважины с глубиной, конструкцией, датой и замеренным дебитом,
  гарантия на работы и документы на оборудование. Этого достаточно, чтобы
  скважину можно было обслуживать у любого подрядчика, а при продаже дома —
  показать покупателю.
</p>

<h2>Что делать, если скважина уже есть</h2>
<p>
  Иногда «под ключ» нужно не с нуля: скважина пробурена, но не обустроена, либо
  обустроена летним вариантом, а хочется круглогодичный. Мы такие объекты берём —
  <a href="<?= e(u('/uslugi/remont/')) ?>">приедем, посмотрим состояние ствола</a>
  и скажем честно, дешевле её доводить или бурить новую.
</p>
