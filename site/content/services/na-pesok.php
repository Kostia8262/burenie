<p>
  Скважина на песок берёт воду из водоносного песчаного слоя, который в
  Донбассе обычно залегает на 22–45 метрах. Это самый быстрый и самый дешёвый
  способ получить на участке собственную воду — с оговорками, про которые
  честно стоит знать заранее.
</p>

<h2>Как устроена такая скважина</h2>
<p>
  В пробуренный ствол опускается обсадная труба, в нижней части которой стоит
  фильтр — сетка из нержавеющей стали. Размер ячейки подбирается под фракцию
  песка на вашем участке: слишком крупная пропустит песок в дом, слишком мелкая
  быстро заилится и задушит дебит. Поэтому фильтр — это не «одинаковая деталь
  из прайса», а подбор под конкретный грунт.
</p>

<h2>Чего ждать по цифрам</h2>
<ul>
  <li>глубина: обычно 22–45 метров;</li>
  <li>дебит: около 1 м³/ч — хватает дому и поливу, но не бассейну на постоянном доливе;</li>
  <li>срок службы: 5–15 лет, сильно зависит от того, как скважину эксплуатируют;</li>
  <li>сроки работ: как правило, один день.</li>
</ul>

<h2>Плюсы</h2>
<ul>
  <li>дешевле артезианской в разы;</li>
  <li>бурится за день, малогабаритной установкой прямо во дворе;</li>
  <li>подходит недорогой насос — экономия ещё и на оборудовании;</li>
  <li>меньше диаметр ствола, меньше грязи на участке.</li>
</ul>

<h2>Минусы, о которых надо знать до начала</h2>
<ul>
  <li>песчаный горизонт есть не на каждом участке — его может просто не оказаться;</li>
  <li>дебит ниже, чем у артезианской, и летом может проседать;</li>
  <li>горизонт хуже защищён сверху, поэтому анализ воды обязателен;</li>
  <li>без регулярного использования скважина заиливается быстрее.</li>
</ul>

