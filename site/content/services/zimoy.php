<p>
  Зима — не повод откладывать скважину до весны. Мороз держит верхний метр
  грунта, а всё, что ниже, буровой установке безразлично: температура на
  глубине стабильная круглый год.
</p>

<h2>Что реально меняется зимой</h2>
<ul>
  <li>первый метр идёт медленнее — мёрзлый слой приходится проходить аккуратнее;</li>
  <li>воду для промывки возим тёплой, чтобы не прихватывало;</li>
  <li>траншею под ввод в дом копать тяжелее, иногда её переносят на весну;</li>
  <li>обустройство планируем так, чтобы ничего не оставалось замерзать.</li>
</ul>

<h2>Чем зима даже удобнее</h2>
<ul>
  <li>очередь короче — основной поток заказов идёт весной и летом;</li>
  <li>по мёрзлой земле техника не оставляет колеи, участок не раскисает;</li>
  <li>грядки и газон уже не жалко — сезон закончился;</li>
  <li>к весне вода на участке уже есть, и поливать можно с первого дня.</li>
</ul>

<h2>Что с обустройством</h2>
<p>
  Зимой особенно важно, чтобы оборудование не осталось на морозе. Летний
  вариант зимой не делают — либо
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a>, либо
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a>, оба ставятся ниже глубины
  промерзания. Если траншею до дома копать нет возможности, скважину можно
  законсервировать до весны: устье закрывается, оборудование не монтируется,
  вода в трубе не остаётся.
</p>

<h2>Когда бурить всё-таки не стоит</h2>
<p>
  В сильный затяжной мороз ниже −20 °C работа идёт заметно медленнее, и мы честно
  предупреждаем об этом заранее, а не выставляем потом счёт за простой.
</p>
