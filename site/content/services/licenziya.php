<h2>Когда лицензия физлицу не нужна</h2>
<p>
  Как правило, она не требуется, если одновременно выполняются три условия:
</p>
<ul>
  <li>скважина на своём участке и используется только для нужд семьи;</li>
  <li>вода не идёт на продажу и не используется в предпринимательской деятельности;</li>
  <li>забор ведётся из горизонта, который не является источником централизованного
      водоснабжения, и в объёмах бытового потребления.</li>
</ul>
<p>
  Под это описание попадает подавляющее большинство скважин в частном секторе —
  и на песок, и неглубокие артезианские.
</p>

<h2>Когда лицензия нужна</h2>
<ul>
  <li>скважину использует юридическое лицо или ИП в своей деятельности;</li>
  <li>вода идёт на производство, мойку, ферму, теплицы, базу отдыха;</li>
  <li>водой пользуется несколько домовладений или целый посёлок;</li>
  <li>объёмы выходят за рамки бытового потребления;</li>
  <li>забор ведётся из горизонта, используемого для централизованного водоснабжения.</li>
</ul>

<h2>Что нужно сделать для получения</h2>
<ul>
  <li>собрать документы на участок и обоснование потребности в воде;</li>
  <li>подготовить проект зоны санитарной охраны;</li>
  <li>сделать анализ воды в аккредитованной лаборатории;</li>
  <li>оформить паспорт скважины с конструкцией и замеренным дебитом;</li>
  <li>подать пакет в уполномоченный орган и пройти согласование.</li>
</ul>

