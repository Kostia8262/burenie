<p>
  Малогабаритная буровая установка (МГБУ) — компактная машина на раме, которую
  можно закатить туда, куда крупная техника не попадёт в принципе. Для частного
  сектора Донецка и Макеевки, где дворы тесные, а въезд часто шириной в калитку,
  это обычно единственный рабочий вариант.
</p>

<h2>Что нужно установке на участке</h2>
<ul>
  <li>проход шириной от 90 см — то есть обычная калитка;</li>
  <li>площадка примерно 2×3 метра под саму установку;</li>
  <li>высота от 3 метров над точкой бурения;</li>
  <li>вода для промывки — привезём, если на участке её нет;</li>
  <li>электричество 220 В поблизости (или работаем от генератора).</li>
</ul>

