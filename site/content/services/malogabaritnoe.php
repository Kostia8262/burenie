<h2>Чем МГБУ отличается от крупной установки</h2>
<p>
  Большая установка на шасси бурит быстрее и уходит глубже, но ей нужен въезд,
  разворот и площадка, которой в частном секторе просто нет. Малогабаритная
  установка идёт медленнее, зато работает во дворе, в теплице, в гараже и даже
  в подвале — и после неё не остаётся раздавленного газона и колеи через весь
  участок.
</p>

