  <li>абиссинские скважины на малой глубине, когда горизонт близко.</li>
</ul>

<h2>Сколько грязи будет</h2>
<p>
  Бурение идёт с промывкой, поэтому наверх поднимается вода с размытым грунтом.
  Мы заранее договариваемся, куда её отводить, и подкладываем щиты под
  установку. Площадка после работы остаётся в рабочем виде, но сажать газон
  ровно на месте бурения в этом сезоне не стоит.
</p>
