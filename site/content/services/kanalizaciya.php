<p>
  Как только в доме появляется вода, сразу возникает вопрос, куда её девать.
  Выбор зависит от двух вещей: сколько человек живёт в доме и круглый ли год,
  и какой на участке грунт.
</p>

<h2>Три рабочих варианта</h2>

<h3>Накопительная ёмкость</h3>
<p>
  Герметичный бак, который откачивает ассенизатор. Дешевле всего на старте,
  не требует ухода, не зависит от грунта. Но чем больше воды вы тратите, тем
  чаще приезжает машина — для дома постоянного проживания это быстро выходит
  дороже всего остального.
</p>

<h3>Септик с почвенной доочисткой</h3>
<p>
  Стоки отстаиваются, осветлённая вода уходит в фильтрующее поле или колодец.
  Золотая середина по деньгам и обслуживанию. Требует, чтобы грунт впитывал
  воду: на плотной глине или при высоких грунтовых водах поле работать не будет,
  и это нужно проверять до покупки септика, а не после.
</p>

<h3>Станция биологической очистки</h3>
<p>
  Компактная, даёт воду, которую можно сбрасывать в канаву или на рельеф,
  работает при любом грунте. Дороже, требует электричества круглосуточно и не
  любит длительных перерывов в работе — на сезонной даче бактерии просто
  погибнут.
</p>

<h2>Как выбрать</h2>
<ul>
  <li>сезонная дача, мало воды — накопитель;</li>
  <li>постоянный дом, грунт впитывает — септик с полем фильтрации;</li>
  <li>постоянный дом, глина или высокая вода — станция биоочистки;</li>
  <li>дом с большим расходом и несколькими санузлами — считаем объём отдельно.</li>
</ul>

<h2>Что мы делаем</h2>
<p>
  Смотрим участок, оцениваем грунт и уровень грунтовых вод, считаем объём по
  числу жильцов, подбираем систему, монтируем и подключаем. Земляные работы —
  наши, отдельного подрядчика искать не нужно.
</p>

<h2>Важно про расстояния</h2>
<p>
  Септик и поле фильтрации нельзя ставить вплотную к скважине: между ними должно
  быть выдержано расстояние, иначе есть риск загрязнить собственный водозабор.
  Мы планируем обе системы вместе, даже если делаем их в разное время — скажите
  заранее, что планируете канализацию, и мы учтём это при выборе места скважины.
</p>
