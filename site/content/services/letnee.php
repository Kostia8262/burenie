<p>
  Летнее обустройство — самый дешёвый способ начать пользоваться скважиной.
  Ставится оголовок, опускается насос, выводится кран или летний водопровод для
  полива. Зимой система сливается, весной запускается обратно.
</p>

<h2>Что входит</h2>
<ul>
  <li>герметичный оголовок на устье;</li>
  <li>скважинный насос с тросом и кабелем;</li>
  <li>шланг или труба по поверхности до точек разбора;</li>
  <li>кран, при желании — простая автоматика и гидроаккумулятор;</li>
  <li>инструктаж, как слить воду перед морозами.</li>
</ul>

<h2>Кому подходит</h2>
<ul>
  <li>дачам, где живут с весны до осени;</li>
  <li>участкам, где вода нужна прежде всего для полива;</li>
  <li>тем, кто хочет сначала убедиться в дебите, а обустраиваться капитально позже;</li>
  <li>случаям, когда бюджет сейчас ограничен, а вода нужна уже.</li>
</ul>

<h2>Чего ждать не стоит</h2>
<p>
  Зимой такой системой пользоваться нельзя: труба по поверхности замёрзнет.
  Если в доме живут круглый год, летний вариант — только временная мера, и
  деньги за него потом частично уйдут в никуда. В этом случае честнее сразу
  делать <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a> или
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a>.
</p>

<h2>Можно ли потом достроить до зимнего</h2>
<p>
  Да, и мы изначально монтируем так, чтобы это было возможно: насос, кабель и
  оголовок остаются, добавляются траншея, адаптер или кессон и ввод в дом.
  Скажите на выезде, что планируете переход на круглогодичный вариант — учтём
  это в схеме.
</p>
