<p>
  Вода из скважины — это не дистиллят. Она проходит через породу и приносит с
  собой всё, что в этой породе растворено. В Донбассе чаще всего приходится
  иметь дело с жёсткостью и железом, реже — с сероводородом и нитратами.
</p>

<h2>Порядок всегда один: сначала анализ</h2>
<p>
  Подбирать фильтры без протокола анализа — это продавать наугад. Сначала
  <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">берём пробу</a>, получаем цифры,
  и только потом считаем систему. Иначе легко поставить умягчитель там, где
  нужно обезжелезивание, и наоборот.
</p>

<h2>Что обычно приходится убирать</h2>
<ul>
  <li><b>Железо.</b> Вода из крана прозрачная, но, постояв, желтеет; на сантехнике рыжие подтёки.</li>
  <li><b>Жёсткость.</b> Накипь в чайнике и бойлере, перерасход порошка, плёнка на чае.</li>
  <li><b>Сероводород.</b> Запах тухлых яиц, особенно из глубоких горизонтов.</li>
  <li><b>Механика.</b> Песок и взвесь — чаще у скважин на песок с изношенным фильтром.</li>
  <li><b>Нитраты.</b> Признак верховодки: стоки и удобрения с поверхности.</li>
</ul>

<h2>Из чего собирается система</h2>
<ul>
  <li>механический фильтр грубой очистки — первым, чтобы не убить остальное;</li>
  <li>обезжелезиватель — с аэрацией или на засыпке, в зависимости от формы железа;</li>
  <li>умягчитель на ионообменной смоле — против жёсткости;</li>
  <li>угольный фильтр — против запаха и привкуса;</li>
  <li>питьевой узел на кухню, если нужна вода под питьё отдельно.</li>
</ul>

<h2>Обслуживание</h2>
<p>
  Любая система — это не «поставил и забыл»: засыпку надо промывать, соль в
  умягчителе досыпать, картриджи менять. Мы показываем, как это делать
  самостоятельно, и приезжаем на обслуживание, если делать этого не хочется.
</p>

<h2>Чего мы не делаем</h2>
<p>
  Не продаём «универсальный комплект на любую воду». Такого не бывает: набор
  фильтров под жёсткую артезианскую воду и под воду с железом из песчаного
  горизонта — это разные системы и разные деньги.
</p>
