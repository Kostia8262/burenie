</p>

<h2>Мы бурили не мы — возьмётесь?</h2>
<p>
  Да. Чужие скважины берём. Единственное, о чём попросим — вспомнить или найти
  паспорт: глубина и конструкция сильно ускоряют диагностику. Если паспорта нет,
  замерим всё сами.
</p>
