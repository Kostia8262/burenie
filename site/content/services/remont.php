<p>
  Скважина не вечная, но и не одноразовая. Большинство проблем — упавший дебит,
  песок в воде, заклинивший насос — решаются без бурения новой. Начинаем всегда
  с диагностики, а не с предложения бурить заново.
</p>

<h2>С чем к нам обращаются</h2>
<ul>
  <li><b>Упал дебит.</b> Воды стало заметно меньше, насос чаще уходит в сухой ход.</li>
  <li><b>Пошёл песок.</b> Взвесь в воде, песок в фильтрах и бачке унитаза.</li>
  <li><b>Насос не поднимается.</b> Заклинило, прикипело, оборвало трос.</li>
  <li><b>Вода помутнела или изменила запах.</b> Возможна разгерметизация обсадки.</li>
  <li><b>Скважина простояла несколько лет.</b> Нужен запуск и прокачка.</li>
</ul>

<h2>Что мы делаем</h2>
<ul>
  <li>замеряем статический и динамический уровень, считаем фактический дебит;</li>
  <li>поднимаем насос и осматриваем его состояние;</li>
  <li>при необходимости проводим видеодиагностику ствола;</li>
  <li>прокачиваем и промываем фильтровую зону;</li>
  <li>извлекаем упавшие предметы и застрявшее оборудование;</li>
  <li>меняем насос, трос, кабель, оголовок, элементы обвязки.</li>
</ul>

<h2>Почему падает дебит</h2>
<p>
  Чаще всего фильтр зарастает: мелкие частицы и соли железа постепенно
  закупоривают сетку. Вторая причина — редкое использование: скважина, которой
  пользуются раз в месяц, заиливается быстрее, чем рабочая. Третья — насос
  подобран мощнее, чем скважина может отдать, и она просто не успевает
  восстанавливаться.
</p>

<h2>Когда честнее бурить новую</h2>
<p>
