<p>
  Скважинный адаптер — латунный узел, который выводит трубу из обсадной колонны
  вбок, ниже глубины промерзания. Всё соединение остаётся под землёй: на участке
  не появляется ни люка, ни бетонного короба, ни бугра посреди газона.
</p>

<h2>Как это работает</h2>
<p>
  Адаптер состоит из двух частей. Наружная врезается в обсадную трубу на глубине
  примерно 1,5–2 метра и соединяется с трубой, идущей в дом. Внутренняя
  закреплена на напорной трубе насоса и заходит в наружную по принципу
  «ласточкиного хвоста». Чтобы достать насос, части разъединяются штангой прямо
  через устье — раскапывать ничего не нужно.
</p>

<h2>Этапы монтажа</h2>
<ul>
  <li>копаем приямок у скважины и траншею до дома ниже промерзания;</li>
  <li>врезаем наружную часть адаптера в обсадную трубу;</li>
  <li>опускаем насос с закреплённой внутренней частью и стыкуем;</li>
  <li>ставим оголовок, герметизируем устье;</li>
  <li>заводим трубу и кабель в дом, монтируем автоматику и гидроаккумулятор;</li>
  <li>засыпаем траншею, запускаем систему и проверяем под нагрузкой.</li>
</ul>

<h2>Плюсы</h2>
<ul>
  <li>заметно дешевле кессона;</li>
  <li>на участке ничего не торчит — можно сажать газон прямо над скважиной;</li>
  <li>нечему промерзать: всё соединение ниже линии промерзания;</li>
  <li>монтаж быстрее, земляных работ меньше.</li>
</ul>

<h2>Минусы</h2>
<ul>
  <li>к оборудованию нет свободного доступа — всё обслуживание через устье;</li>
  <li>врезка в обсадную трубу должна быть сделана аккуратно, иначе возможна течь;</li>
  <li>не годится, если в приямке высоко стоят грунтовые воды.</li>
</ul>

