<h2>Как обычно выглядит дачная скважина</h2>
<ul>
  <li><a href="<?= e(u('/uslugi/na-pesok/')) ?>">скважина на песок</a> глубиной 22–45 метров;</li>
  <li>бурение <a href="<?= e(u('/uslugi/malogabaritnoe/')) ?>">малогабаритной установкой</a> — проходит в дачную калитку;</li>
  <li><a href="<?= e(u('/uslugi/letnee/')) ?>">летнее обустройство</a>: оголовок, насос, кран, полив;</li>
  <li>один день работы, вода из устья идёт в тот же день.</li>
</ul>

<h2>Почему МГБУ для дачи — почти всегда правильный выбор</h2>
<p>
  На дачных участках узкие проезды, тесные проходы между домом и забором,
  теплицы и посадки. Крупная техника туда либо не заедет, либо заедет ценой
  снесённого забора и раздавленных грядок. Малогабаритная установка
  разворачивается на площадке 2×3 метра и проходит в проём 90 см.
</p>

<h2>Сколько воды даст такая скважина</h2>
<p>
  Песчаный горизонт обычно отдаёт около кубометра в час. Для полива, душа,
  бытовых нужд и наполнения бочки этого хватает с запасом. Для бассейна на
  постоянном доливе или для нескольких участков сразу — уже нет, тут нужно
  считать отдельно.
</p>

<h2>Что делать перед зимой</h2>
<p>
  Летнюю систему нужно слить: вынуть шланги, спустить воду из трубы и
  гидроаккумулятора, закрыть устье. Мы показываем это на сдаче объекта —
  процедура на десять минут, но если её пропустить, весной придётся менять трубу.
</p>

<h2>Если дача станет домом</h2>
<p>
  Скажите об этом сразу. Мы заложим схему так, чтобы позже добавить
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a> и ввод в дом, не
  переделывая всё с нуля.
</p>
