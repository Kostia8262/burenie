<p>
  Артезианская скважина идёт до известнякового горизонта — в Донбассе это
  обычно глубже 70 метров. Вода там лежит под двумя водоупорами, поэтому не
  зависит ни от дождей, ни от засухи, ни от того, что делают соседи на своих
  участках.
</p>

<h2>Чем она лучше песчаной</h2>
<ul>
  <li>стабильный дебит — его хватает дому, поливу и хозяйству одновременно;</li>
  <li>вода не проседает в засушливое лето;</li>
  <li>горизонт закрыт сверху плотной глиной, верховодка туда не попадает;</li>
  <li>срок службы измеряется десятилетиями, а не годами;</li>
  <li>фильтр в классическом виде не нужен — вода идёт из трещин известняка.</li>
</ul>

<h2>Чем хуже</h2>
<ul>
  <li>дороже: больше метров и больше обсадной трубы;</li>
  <li>дольше: несколько дней вместо одного;</li>
  <li>вода часто жёсткая и с железом — почти всегда нужна
      <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистка</a>;</li>
  <li>для юрлиц и больших объёмов потребуется
      <a href="<?= e(u('/uslugi/licenziya/')) ?>">лицензия</a>.</li>
</ul>

<h2>Когда переплата оправдана</h2>
<p>
  Если дом постоянного проживания, если на участке теплицы или скотина, если
  воду берут несколько семей — артезианская окупается уже тем, что не придётся
  через несколько лет бурить вторую скважину рядом. Если это дача на сезон и
  полив грядок — скорее всего, хватит
  <a href="<?= e(u('/uslugi/na-pesok/')) ?>">скважины на песок</a>.
</p>

<h2>Что мы делаем перед бурением</h2>
<p>
  Спрашиваем про скважины у соседей и смотрим участок. По глубине соседских
  скважин обычно уже понятно, где лежит известняк и на что рассчитывать. Это
  бесплатно и ни к чему вас не обязывает.
</p>
