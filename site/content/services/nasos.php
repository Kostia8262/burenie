<p>
  Насос подбирают не «помощнее, чтобы с запасом», а под конкретную скважину.
  Слишком слабый не дотянет воду до верхних точек, слишком мощный будет
  выкачивать скважину быстрее, чем она восстанавливается, ловить сухой ход и
  жечь обмотку.
</p>

<h2>Что мы считаем перед покупкой</h2>
<ul>
  <li>динамический уровень воды — на какой глубине он стоит при работе насоса;</li>
  <li>дебит скважины — сколько она реально отдаёт в час;</li>
  <li>высоту подъёма до самой верхней точки разбора;</li>
  <li>длину трассы и потери давления в трубе;</li>
  <li>сколько точек могут работать одновременно;</li>
  <li>диаметр обсадной трубы — он ограничивает габарит насоса.</li>
</ul>

<h2>Что входит в монтаж</h2>
<ul>
  <li>насос на тросе нужной длины, с кабелем и обратным клапаном;</li>
  <li>гидроаккумулятор и реле давления под ваш режим потребления;</li>
  <li>защита от сухого хода — обязательна, а не «по желанию»;</li>
  <li>манометр и запорная арматура;</li>
  <li>пусконаладка и проверка под реальной нагрузкой.</li>
</ul>

<h2>Почему защита от сухого хода обязательна</h2>
<p>
  Скважинный насос охлаждается той водой, которую качает. Если уровень упал —
  например, в засушливый август или при слишком большом отборе — насос
  продолжает работать «на воздухе» и сгорает за считаные минуты. Реле сухого
  хода стоит несопоставимо дешевле нового насоса.
</p>

<h2>Замена насоса в существующей скважине</h2>
<p>
  Приедем, достанем старый, замерим уровень и дебит, подберём новый по факту, а
  не по тому, что стояло раньше. Если насос заклинило или оборвало трос — это
  тоже решаемо, см. <a href="<?= e(u('/uslugi/remont/')) ?>">ремонт скважин</a>.
</p>
