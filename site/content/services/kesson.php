<p>
  Кессон — герметичная ёмкость, которую закапывают над устьем скважины. Внутри
  помещаются оголовок, гидроаккумулятор, автоматика и запорная арматура, и ко
  всему этому можно спуститься в любой мороз, не раскапывая участок.
</p>

<h2>Что внутри</h2>
<ul>
  <li>оголовок скважины и выход напорной трубы;</li>
  <li>гидроаккумулятор и реле давления;</li>
  <li>манометр, краны, фильтр грубой очистки;</li>
  <li>электрика насоса и защита от сухого хода;</li>
  <li>вывод трубы в сторону дома ниже глубины промерзания.</li>
</ul>

<h2>Когда нужен именно кессон</h2>
<ul>
  <li>вы хотите иметь доступ к оборудованию, не вызывая бригаду;</li>
  <li>оборудование не помещается в доме или его туда не хочется ставить;</li>
  <li>высокий уровень грунтовых вод — адаптер в таком приямке работать не будет;</li>
  <li>скважина далеко от дома, и часть обвязки логично держать у устья.</li>
</ul>

<h2>Из чего бывают кессоны</h2>
<p>
  Пластиковые — самые распространённые: не ржавеют, лёгкие, герметичные,
  ставятся за день. Металлические дешевле в закупке, но требуют гидроизоляции и
  со временем корродируют. Бетонные кольца дёшевы, но почти никогда не бывают
  по-настоящему герметичными — в них попадает вода. Мы по умолчанию ставим
  пластик и объясняем, если в вашем случае есть смысл в другом.
</p>

<h2>Что важно при монтаже</h2>
<p>
  Пластиковый кессон в обводнённом грунте может вытолкнуть наверх, поэтому его
  закрепляют — бетонной плитой или якорением. Если этого не сделать, через
  сезон-другой крышка окажется выше уровня земли. На этом чаще всего и горят
  дешёвые монтажи.
</p>

