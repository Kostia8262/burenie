<h2>Чем задача юрлица отличается от частной</h2>
<p>
  Частному дому обычно хватает дебита около кубометра в час. Производству,
  теплицам или мойке нужно считать пиковое потребление, а не среднее: скважина,
  которой хватает «в целом за сутки», может не тянуть смену в пиковые часы.
  Поэтому мы начинаем не с глубины, а с вопроса, сколько кубов и когда вам
  реально нужно.
</p>

