<p>
  Анализ воды — это не формальность и не способ продать фильтры. Без протокола
  невозможно подобрать
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистку</a>, а у воды из
  верхних горизонтов ещё и нужно проверить, можно ли её вообще пить.
</p>

<h2>Когда сдавать</h2>
<ul>
  <li>после бурения и прокачки новой скважины — обязательно;</li>
  <li>раз в год-два для действующей скважины;</li>
  <li>если изменились вкус, запах, цвет или появился осадок;</li>
  <li>перед покупкой системы водоочистки;</li>
  <li>если рядом появился септик, ферма или поля с удобрениями.</li>
</ul>

<h2>Как правильно взять пробу</h2>
<p>
  Пробу нельзя набрать в пластиковую бутылку из-под лимонада и отвезти через
  три дня. Нужна чистая тара, слив воды перед отбором, заполнение без воздушного
  пузыря и доставка в лабораторию в течение нескольких часов. Мы отбираем пробу
  сами и везём её по правилам — иначе протокол покажет не вашу воду, а вашу
  бутылку.
</p>

<h2>Что смотрим в протоколе</h2>
<ul>
  <li><b>Железо.</b> Самая частая проблема в регионе: рыжие подтёки, осадок при отстаивании.</li>
  <li><b>Жёсткость.</b> Накипь, перерасход моющих, плёнка на чае.</li>
  <li><b>Сероводород.</b> Запах, характерный для глубоких горизонтов.</li>
  <li><b>Нитраты и нитриты.</b> Маркер попадания поверхностных стоков.</li>
  <li><b>Мутность и взвешенные вещества.</b> Часто указывают на проблему с фильтром скважины.</li>
  <li><b>Микробиология.</b> Отдельный анализ, критичен для неглубоких скважин.</li>
</ul>

