<p>
  Дебит упал, напор просел, из крана пошёл песок или мутная взвесь. Обычно это
  не конец скважины, а заиливание — постепенное зарастание фильтровой зоны.
  Разберём причины и что с этим делают.
</p>

<h2>Признаки</h2>
<ul>
  <li>воды стало заметно меньше, насос чаще выключается по сухому ходу;</li>
  <li>в воде песок и взвесь, забиваются фильтры и сетки на смесителях;</li>
  <li>вода мутнеет после простоя, а через несколько минут прокачки светлеет;</li>
  <li>насос гудит громче обычного или греется.</li>
</ul>

<h2>Почему это происходит</h2>

<h3>Скважиной мало пользуются</h3>
<p>
  Главная причина. Рабочая скважина сама себя промывает потоком. Скважина,
  из которой качают раз в месяц, заиливается за пару сезонов. Дачные скважины
  страдают от этого чаще всего.
</p>

<h3>Насос мощнее, чем скважина</h3>
<p>
  Избыточный отбор взмучивает придонный слой и затягивает мелочь в фильтр.
  <a href="<?= e(u('/stati/kak-vybrat-nasos/')) ?>">Подбор насоса по дебиту</a>
  решает эту проблему на корню.
</p>

<h3>Неправильно подобранный фильтр</h3>
<p>
  Слишком мелкая ячейка забивается, слишком крупная пропускает песок внутрь и
  он копится на забое. Это закладывается ещё на этапе бурения.
</p>

<h3>Вибрационный насос</h3>
<p>
  Вибрация разрушает стенки и фильтровую зону. В скважине ему не место.
</p>

<h3>Отложения железа</h3>
<p>
  В воде с высоким железом на сетке фильтра со временем нарастает плотная
  корка. Тут помогает только промывка, и делать её нужно регулярно.
</p>

<h2>Что делают для восстановления</h2>
<ul>
  <li><b>Прокачка.</b> Мощным насосом выносят осадок с забоя. Самый простой и
      частый способ, часто его достаточно.</li>
  <li><b>Промывка фильтровой зоны.</b> Подача воды под давлением через
      промывочную колонну.</li>
  <li><b>Продувка сжатым воздухом (эрлифт).</b> Для более плотных отложений.</li>
  <li><b>Химическая обработка.</b> Против железистых и известковых корок,
      применяется аккуратно и не в каждой скважине.</li>
  <li><b>Видеодиагностика ствола.</b> Когда непонятно, что именно произошло.</li>
</ul>

<h2>Чего делать не стоит самому</h2>
<p>
  Не пытайтесь «пробить» скважину трубой или тросом — легко повредить
  обсадную колонну или уронить предмет на забой, после чего доставать его будет
  отдельной дорогой работой. И не лейте в скважину бытовую химию: то, что
  растворит налёт, вы потом будете пить.
</p>

<h2>Когда восстанавливать уже нечего</h2>
<p>
  Если нарушена обсадная колонна, если ствол засыпан на значительную высоту,
  если горизонт выработан — ремонт обойдётся дороже новой скважины и прослужит
  недолго. Мы говорим об этом прямо, даже когда ремонт был бы для нас выгоднее.
</p>

<h2>Как не доводить до этого</h2>
<ul>
  <li>пользуйтесь скважиной регулярно, хотя бы понемногу;</li>
  <li>раз в сезон прокачивайте её на полный поток;</li>
  <li>не ставьте насос мощнее, чем нужно;</li>
  <li>держите устье герметичным;</li>
  <li>сдавайте <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">воду на анализ</a> —
      изменения в составе часто заметны раньше, чем падает дебит.</li>
</ul>

<p>
