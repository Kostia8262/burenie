<p>
  Скважинный насос выбирают по двум числам: напор и подача. Оба считаются от
  вашей скважины и вашего дома, а не по принципу «возьму помощнее, пусть будет
  запас». Запас здесь работает против вас.
</p>

<h2>Что нужно знать до покупки</h2>
<ul>
  <li><b>Динамический уровень.</b> На какой глубине стоит вода, когда насос
      работает. Именно от него считается высота подъёма, а не от глубины скважины.</li>
  <li><b>Дебит скважины.</b> Сколько кубометров в час она отдаёт устойчиво.</li>
  <li><b>Высота до верхней точки разбора.</b> Второй этаж, чердак, душ.</li>
  <li><b>Длина и диаметр трубы до дома.</b> Каждый десяток метров и каждый
      поворот съедают часть напора.</li>
  <li><b>Диаметр обсадной трубы.</b> Он ограничивает габарит насоса.</li>
</ul>

<h2>Как считается напор</h2>
<p>
  Грубо: динамический уровень + высота до верхней точки + потери в трубе +
  запас на рабочее давление в системе. Сумма в метрах и есть требуемый напор.
  На практике к расчёту добавляют небольшой резерв, но именно небольшой.
</p>

<h2>Как считается подача</h2>
<p>
  Считают не сумму всех точек, а реалистичный пик: например, душ и кухня
  одновременно. И самое главное — <b>подача насоса не должна превышать дебит
  скважины</b>. Если насос качает больше, чем скважина отдаёт, уровень падает
  до заборной решётки, и насос начинает работать всухую.
</p>

<h2>Почему «помощнее» — плохая идея</h2>
<p>
  Скважинный насос охлаждается водой, которую качает. Избыточно мощный насос
  осушает скважину быстрее, чем она восстанавливается, и сгорает. Плюс он
  сильнее взмучивает придонный слой, ускоряя
  <a href="<?= e(u('/stati/skvazhina-zailila/')) ?>">заиливание</a>.
</p>

<h2>Что ставится вместе с насосом</h2>
<ul>
  <li><b>Реле сухого хода</b> — обязательно. Стоит копейки по сравнению с насосом.</li>
  <li><b>Гидроаккумулятор</b> — сглаживает давление, снижает число пусков.</li>
  <li><b>Реле давления и манометр</b> — чтобы система знала, когда включаться.</li>
  <li><b>Обратный клапан</b> — держит столб воды в трубе.</li>
  <li><b>Трос из нержавейки</b> — на нём насос висит годами, экономить здесь нельзя.</li>
</ul>

<h2>Вибрационные насосы</h2>
<p>
  Знаменитый недорогой «вибрационник» в скважине лучше не использовать.
  Вибрация разрушает фильтровую зону и стенки ствола, скважина заиливается
  заметно быстрее. Для временной прокачки он иногда годится, для постоянной
  работы — нет.
</p>

<h2>На какой глубине вешать насос</h2>
<p>
  Ниже динамического уровня, но выше зоны фильтра и придонного осадка. Точную
  отметку берут из паспорта скважины — ещё одна причина, по которой
  <a href="<?= e(u('/stati/kak-prinyat-skvazhinu/')) ?>">паспорт стоит требовать при сдаче</a>.
</p>

