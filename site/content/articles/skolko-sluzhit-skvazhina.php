<h2>Что сокращает жизнь скважины</h2>
<ul>
  <li><b>Редкое использование.</b> Главный враг. Скважина без потока
      <a href="<?= e(u('/stati/skvazhina-zailila/')) ?>">заиливается</a> за
      пару сезонов.</li>
  <li><b>Слишком мощный насос.</b> Постоянный переотбор взмучивает забой.</li>
  <li><b>Вибрационный насос.</b> Разрушает фильтровую зону и стенки.</li>
  <li><b>Негерметичное устье.</b> Внутрь идут поверхностная вода, грязь, мусор.</li>
  <li><b>Экономия на обсадной трубе.</b> Тонкая стенка деформируется и
      пропускает верховодку.</li>
  <li><b>Отсутствие обслуживания.</b> Скважину, как и котёл, надо иногда
      обслуживать.</li>
</ul>

<h2>Что продлевает</h2>
<ul>
  <li>регулярный отбор воды, хотя бы небольшой, круглый год;</li>
  <li>сезонная прокачка на полный поток;</li>
  <li>насос, подобранный <a href="<?= e(u('/stati/kak-vybrat-nasos/')) ?>">по дебиту</a>,
      а не «с запасом»;</li>
  <li>герметичный оголовок и целая обвязка;</li>
  <li>ежегодный <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ воды</a> —
      изменения в составе видны раньше, чем падение дебита;</li>
  <li>паспорт скважины под рукой: без него любое обслуживание начинается
      с замеров заново.</li>
</ul>

<h2>Что происходит в конце срока</h2>
<p>
  Скважина не перестаёт работать внезапно. Сначала постепенно падает дебит,
  потом появляется песок, потом вода начинает мутнеть после каждого простоя.
  На этом этапе её ещё можно восстановить прокачкой и промывкой, и часто это
  даёт ещё несколько лет.
</p>

<h2>Когда дешевле бурить новую</h2>
<p>
  Если нарушена обсадная колонна, если ствол засыпан на значительную высоту,
  если горизонт выработан. Восстановление в таких случаях стоит сопоставимо с
  новой скважиной и служит недолго. Мы говорим об этом прямо —
  <a href="<?= e(u('/uslugi/remont/')) ?>">приезжаем, диагностируем и считаем
  оба варианта</a>.
</p>

<h2>Про горизонт планирования</h2>
<p>
  Если дом строится надолго, стоит честно посчитать: две скважины на песок
  подряд за двадцать лет обойдутся дороже одной
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">артезианской</a>. Если это
  дача и вода нужна три месяца в году — переплата не окупится.
  <a href="<?= e(u('/stati/pesok-ili-izvestnyak/')) ?>">Сравнение горизонтов</a>
  есть в отдельной статье.
</p>
