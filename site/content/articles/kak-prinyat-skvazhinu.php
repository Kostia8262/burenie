<p>
  Скважина — это то, что нельзя посмотреть глазами. Всё, что от неё видно, —
  труба из земли. Поэтому приёмка сводится к нескольким проверкам, которые
  стоит сделать до того, как бригада уедет и вы отдадите остаток денег.
</p>

<h2>1. Паспорт скважины</h2>
<p>
  Главный документ. В нём должны быть: адрес, дата, глубина, диаметр и материал
  обсадной трубы, тип и глубина установки фильтра, статический и динамический
  уровень воды, замеренный дебит, геологический разрез по факту бурения.
</p>
<p>
  Без паспорта вы не сможете ни грамотно подобрать новый насос через пять лет,
  ни оформить <a href="<?= e(u('/uslugi/licenziya/')) ?>">лицензию</a>, если она
  понадобится, ни внятно объяснить покупателю при продаже дома, что у вас за
  скважина.
</p>

<h2>2. Замер дебита при вас</h2>
<p>
  Дебит — сколько кубометров в час скважина отдаёт устойчиво, а не в первую
  минуту. Просите замерить при вас и записать в паспорт. Замер делается на
  установившемся режиме: насос работает, уровень стабилизировался, объём
  фиксируется по времени.
</p>
<p>
  Если вам называют дебит без замера — это оценка, и в паспорт она попадать не
  должна.
</p>

<h2>3. Прокачка до чистой воды</h2>
<p>
  Новая скважина всегда даёт мутную воду: в стволе остаётся взвесь после
  бурения. Прокачка идёт до тех пор, пока вода не пойдёт прозрачной. Это часы,
  а не десять минут. Если бригада сворачивается, пока вода ещё мутная, вы
  будете доделывать это сами — своим насосом, который для такой работы не
  предназначен.
</p>

<h2>4. Осмотр устья и оголовка</h2>
<p>
  Оголовок должен быть герметичным: через него в скважину не должны попадать
  вода с поверхности, грязь и грызуны. Труба не должна шататься, вокруг устья
  не должно быть просадки грунта.
</p>

<h2>5. Проверка системы под нагрузкой</h2>
<p>
  Откройте несколько точек одновременно: кухня, душ, полив. Посмотрите, держит
  ли напор, как часто включается насос, не скачет ли давление. Проверьте, что
  реле сухого хода стоит и работает — это то, что спасает насос.
</p>

<h2>6. Документы на оборудование и гарантия</h2>
<p>
  Паспорта на насос, гидроаккумулятор, автоматику. Гарантия отдельно на работы
  и отдельно на оборудование, с понятными сроками и с тем, что именно она
  покрывает.
</p>

<h2>Чего в приёмке быть не должно</h2>
<ul>
  <li>«паспорт вышлем позже» — обычно не высылают;</li>
  <li>«дебит примерно такой» — примерно не бывает, есть замер;</li>
  <li>«вода отстоится сама» — не отстоится, это недокачанная скважина;</li>
  <li>«за прокачку отдельно» — если это не было оговорено в смете заранее.</li>
</ul>

<h2>Через неделю после сдачи</h2>
<p>
  Посмотрите, осталась ли вода такой же прозрачной, не появился ли осадок или
  запах, не просела ли земля вокруг устья. Это лучший момент, чтобы предъявить
  замечания — гарантия свежая, а бригада ещё помнит ваш объект.
</p>
<p>
