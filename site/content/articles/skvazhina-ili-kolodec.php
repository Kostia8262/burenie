<p>
  Колодец кажется проще и понятнее: его видно, из него можно достать воду
  ведром, он не требует электричества. Скважина — дороже на старте и сложнее
  устроена. Разберём по пунктам, где какой вариант действительно выигрывает.
</p>

<h2>Откуда берётся вода</h2>
<p>
  Колодец добирается до
  <a href="<?= e(u('/stati/na-kakuyu-glubinu-burit/')) ?>">верховодки</a> —
  первого водоносного слоя на 8–15 метрах. Этот слой питается осадками и
  напрямую связан с поверхностью. Скважина идёт ниже, под глиняный водоупор,
  который отсекает всё, что течёт сверху.
</p>

<h2>Качество воды</h2>
<p>
  Это главный аргумент, и он не в пользу колодца. В верховодку попадают талые
  воды, стоки, удобрения с полей и огородов, содержимое соседских септиков.
  Вода в колодце может быть прозрачной и вкусной — и при этом не проходить по
  нитратам и микробиологии. В скважину на песок или известняк поверхностная
  вода не попадает.
</p>

<h2>Что происходит в засушливое лето</h2>
<p>
  Колодец мелеет. Это не неисправность, а свойство горизонта: нет дождей — нет
  подпитки. В августе владельцы колодцев обычно и начинают звонить насчёт
  скважины. Песчаный горизонт проседает заметно слабее, артезианский не
  проседает вообще.
</p>

<h2>Деньги</h2>
<p>
  Колодец дешевле на старте, и это его честное преимущество. Но считать нужно
  весь срок: кольца проседают и расходятся, швы текут, раз в несколько лет
  нужна чистка, а если воды перестало хватать — углублять колодец дороже и
  сложнее, чем изначально пробурить скважину.
</p>

<h2>Место на участке</h2>
<p>
  Колодец — это яма метр с лишним в диаметре плюс отмостка плюс подход к нему.
  Скважина с <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптером</a> не занимает
  на поверхности ничего: над ней можно сажать газон.
</p>

<h2>Обслуживание</h2>
<p>
  Колодец нужно чистить, дезинфицировать и следить за кольцами. Скважине нужны
  замена насоса раз в несколько лет и профилактическая прокачка. По трудозатратам
  скважина проще, но её обслуживание требует бригады, а в колодец можно спуститься
  самому — кому что ближе.
</p>

<h2>Где колодец действительно уместен</h2>
<ul>
  <li>воду берут только на полив;</li>
  <li>на участке нет электричества, и вода нужна независимо от него;</li>
  <li>водоносный слой залегает очень близко, а расход маленький;</li>
  <li>колодец уже есть, вода проходит анализ и её хватает.</li>
</ul>

<h2>Где нужна скважина</h2>
<ul>
  <li>вода идёт на питьё и готовку;</li>
  <li>дом постоянного проживания;</li>
  <li>нужен стабильный напор в душе и бойлере;</li>
  <li>рядом поля, фермы, септики соседей;</li>
  <li>летом воды перестаёт хватать.</li>
</ul>

<h2>Короткий вывод</h2>
<p>
  Для полива — колодец, если горизонт близко. Для дома, где пьют воду и живут
  круглый год, — скважина. Промежуточный вариант: оставить колодец на полив и
  пробурить <a href="<?= e(u('/uslugi/na-pesok/')) ?>">скважину на песок</a> под
  дом, так делают довольно часто.
</p>
