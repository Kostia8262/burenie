<h2>Когда переплата за известняк оправдана</h2>
<ul>
  <li>дом постоянного проживания, а не дача;</li>
  <li>воду берут несколько семей или несколько домов;</li>
  <li>есть теплицы, скотина, большой полив;</li>
  <li>на участке уже пробовали бурить на песок и дебита не хватило;</li>
  <li>вы строите надолго и не хотите возвращаться к этому вопросу через десять лет.</li>
</ul>

<h2>Когда песка достаточно</h2>
<ul>
  <li>дача или сезонное проживание;</li>
  <li>вода нужна в основном на полив и бытовые нужды;</li>
  <li>бюджет ограничен здесь и сейчас;</li>
  <li>у соседей такие же скважины и они работают.</li>
</ul>

<h2>Чего делать не надо</h2>
<p>
  Не стоит выбирать горизонт по тому, что дешевле в моменте, если на участке уже
  известно о проблемах с песчаным слоем. Две скважины на песок подряд обходятся
  дороже одной артезианской. И наоборот: бурить 90 метров под дачу, где вода
  нужна три месяца в году, — это деньги, которые никогда не окупятся.
</p>

