<h2>Скважина на песок</h2>
<p>
  Идёт до водоносного песчаного слоя, в Донбассе это обычно 22–45 метров. Воду
  из песка отсекает от ствола фильтр — сетка из нержавейки, подобранная под
  фракцию песка на конкретном участке.
</p>
<ul>
  <li>дебит около 1 м³/ч;</li>
  <li>срок службы 5–15 лет;</li>
  <li>бурится за день;</li>
  <li>подходит недорогой насос;</li>
  <li>есть не на каждом участке.</li>
</ul>

<h2>Артезианская на известняк</h2>
<p>
  Идёт глубже 70 метров, до известнякового горизонта. Вода поступает из трещин
  в породе, классический фильтр не нужен.
</p>
<ul>
  <li>дебит стабильный и заметно выше;</li>
  <li>срок службы — десятилетия;</li>
  <li>не проседает в засуху;</li>
  <li>вода защищена двумя водоупорами;</li>
  <li>почти всегда жёсткая и с железом — нужна
      <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистка</a>.</li>
</ul>

