<p>
  «Приходите весной» — самый частый ответ, который люди слышат зимой. На самом
  деле бурить зимой можно, и в некоторых отношениях это даже удобнее. Разберём,
  что реально меняется.
</p>

<h2>Мороз держит только верхний метр</h2>
<p>
  Глубина промерзания в нашем климате — примерно метр-полтора. Ниже температура
  грунта стабильная круглый год, и породе всё равно, какой месяц на календаре.
  Из 30 или 80 метров проходки мороз влияет на первый метр — и только на
  скорость его прохождения.
</p>

<h2>Что действительно меняется в работе</h2>
<ul>
  <li>первый метр идёт медленнее — мёрзлый слой проходят аккуратнее;</li>
  <li>воду для промывки возят подогретой, чтобы система не прихватывала;</li>
  <li>оборудование и шланги после смены обязательно освобождают от воды;</li>
  <li>траншею под ввод в дом копать тяжелее — иногда её переносят на весну;</li>
  <li>короткий световой день: смена заканчивается раньше.</li>
</ul>

<h2>Чем зима лучше</h2>

<h3>Очередь короче</h3>
<p>
  Основной поток заказов идёт с апреля по сентябрь. Зимой бригада выезжает
  быстрее, и подстроиться под ваш график проще.
</p>

<h3>Участок не страдает</h3>
<p>
  По мёрзлой земле техника не оставляет колеи, грунт не раскисает, газон под
  снегом. Весной от работ остаётся заметно меньше следов, чем если бурить в
  апрельскую распутицу.
</p>

<h3>Ничего не жалко</h3>
<p>
  Сезон закончился: грядки убраны, посадок нет, теплицы пустые. Летом выбор
  места под установку часто упирается именно в то, что жалко потоптать.
</p>

<h3>К весне вода уже есть</h3>
<p>
  Скважина, пробуренная в январе, к началу поливочного сезона уже прокачана,
  обустроена и проверена. Те, кто начинает в апреле, попадают в очередь и
  получают воду к июню.
</p>

<h2>Что с обустройством зимой</h2>
<p>
