  трубе по поверхности на морозе делать нечего. Остаются
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a> и
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a> — оба ставятся ниже
  глубины промерзания.
</p>
<p>
  Если копать траншею до дома сейчас невозможно, скважину консервируют до
  весны: устье герметично закрывают, оборудование не монтируют, воды в трубе не
  оставляют. Весной работы продолжаются с того же места.
</p>

<h2>Когда мы честно советуем подождать</h2>
<p>
  В затяжной мороз ниже −20 °C работа идёт заметно медленнее, и об этом мы
  предупреждаем до выезда, а не выставляем потом счёт за простой. В такие дни
  разумнее сдвинуть работы на неделю.
</p>

