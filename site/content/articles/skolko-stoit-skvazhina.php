<p>
  Это первый вопрос, который нам задают по телефону, и на него невозможно
  ответить одной цифрой. Не потому, что мы что-то скрываем, а потому, что
  скважина в двух соседних дворах может отличаться по цене вдвое. Ниже —
  честный разбор, из чего собирается смета и что стоит проверять в чужих
  предложениях.
</p>

<h2>Смета состоит из четырёх частей</h2>

<h3>1. Проходка — метры</h3>
<p>
  То самое «за метр», которое все вешают на главную страницу. Цена метра
  зависит от породы: песок и глина идут быстро, известняк и твёрдые прослойки
  медленнее, дороже и изнашивают инструмент. Поэтому одинаковая цена метра для
  песчаной и артезианской скважины — это либо усреднение, либо маркетинг.
</p>

<h3>2. Обсадная колонна — труба</h3>
<p>
  Труба держит стенки ствола и отсекает верховодку. Её диаметр определяется
  тем, какой насос туда должен влезть, а материал и толщина стенки — тем,
  сколько скважина должна прослужить. Это вторая по величине статья сметы, и
  именно на ней чаще всего экономят, когда нужно показать красивую цену за метр.
</p>

<h3>3. Обустройство</h3>
<p>
  Разница между вариантами кратная:
  <a href="<?= e(u('/uslugi/letnee/')) ?>">летний</a> — самый дешёвый,
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a> — средний,
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a> — самый дорогой. Сюда же
  входят насос, гидроаккумулятор, автоматика, траншея и ввод трубы в дом.
</p>

<h3>4. Сдача</h3>
<p>
  Прокачка до чистой воды, замер дебита, паспорт скважины. У нас это часть
  работы. Если в чужом предложении прокачка и паспорт идут отдельными
  платными строками — сравнивать цену за метр с нашей уже бессмысленно.
</p>

<h2>Что меняет итоговую сумму</h2>
<ul>
  <li><b>Глубина.</b> Главный множитель. Разница между 30 и 90 метрами — это
      разница в три раза по проходке и по трубе.</li>
  <li><b>Горизонт.</b> <a href="<?= e(u('/uslugi/na-pesok/')) ?>">Песок</a>
      дешевле, <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">известняк</a>
      дороже и надёжнее.</li>
  <li><b>Грунт по пути.</b> Твёрдые прослойки замедляют проходку.</li>
  <li><b>Подъезд.</b> Если установку нужно затаскивать вручную через весь
      участок — это время.</li>
  <li><b>Расстояние до дома.</b> Каждый метр траншеи и трубы стоит денег.</li>
  <li><b>Водоочистка.</b> Выясняется только после
      <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализа воды</a>.</li>
</ul>

<h2>Как читать чужое коммерческое предложение</h2>
<p>
  Низкая цена за метр почти всегда означает одно из трёх: в неё не включена
  обсадная труба; заложена самая тонкая труба из возможных; обустройство
  считается потом по отдельному прайсу. Чтобы сравнить предложения честно,
  спросите у каждого подрядчика одно и то же:
</p>
<ul>
  <li>до какой глубины и на какой горизонт вы идёте;</li>
  <li>какая труба: диаметр, материал, толщина стенки;</li>
  <li>входит ли прокачка и сколько часов;</li>
  <li>что за насос и входит ли он в цену;</li>
  <li>даёте ли паспорт скважины;</li>
  <li>что будет, если горизонт окажется глубже — кто платит за лишние метры.</li>
</ul>
<p>
  Последний вопрос — самый важный. Именно на нём обычно и вырастает смета.
</p>

