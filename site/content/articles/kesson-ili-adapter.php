<p>
  И кессон, и адаптер решают одну задачу: спрятать выход трубы из скважины
  ниже глубины промерзания, чтобы зимой ничего не разорвало. Дальше начинаются
  различия — в цене, в обслуживании и в том, что останется на участке.
</p>

<h2>Адаптер: коротко</h2>
<p>
  Латунный узел врезается в обсадную трубу примерно на 1,5–2 метрах и выводит
  воду вбок, в траншею до дома. Всё под землёй, на поверхности только оголовок
  вровень с грунтом. Насос достаётся штангой через устье, раскапывать ничего
  не нужно.
</p>

<h2>Кессон: коротко</h2>
<p>
  Герметичная ёмкость закапывается над устьем. Внутри помещаются оголовок,
  гидроаккумулятор, автоматика и краны. Сверху — люк, к оборудованию можно
  спуститься в любой мороз.
</p>

