<h2>Когда выбирать адаптер</h2>
<ul>
  <li>бюджет ограничен;</li>
  <li>хочется, чтобы участок остался чистым — газон, дорожка, клумба;</li>
  <li>в доме есть место под гидроаккумулятор и автоматику;</li>
  <li>грунтовые воды стоят низко.</li>
</ul>

<h2>Когда выбирать кессон</h2>
<ul>
  <li>вы хотите сами подходить к оборудованию;</li>
  <li>ставить гидроаккумулятор в доме негде или не хочется;</li>
  <li>высокий уровень грунтовых вод;</li>
  <li>скважина далеко от дома.</li>
</ul>

<h2>Главная ошибка при монтаже кессона</h2>
<p>
  Пластиковый кессон в обводнённом грунте выталкивает наверх, как поплавок.
  Если его не закрепить бетонной плитой или якорем, через сезон-другой крышка
  окажется выше уровня земли, а труба перекосится. Спрашивайте у подрядчика,
  как он планирует закреплять кессон, — это хороший тест.
</p>

<h2>Главная ошибка при монтаже адаптера</h2>
<p>
  Неаккуратная врезка в обсадную трубу. Отверстие делается по месту, и если
  посадка негерметична, через неё в скважину пойдёт верховодка. Такую течь
  сложно найти и неприятно устранять.
</p>

