<p>
  Под Донбассом лежит не одна «вода», а несколько слоёв, и они сильно
  отличаются по качеству, по количеству и по тому, сколько прослужит скважина.
  Разберём, что там внизу и как выбрать, до какого слоя идти.
</p>

<h2>Что лежит под участком</h2>

<h3>0–2 метра: почва и насыпной грунт</h3>
<p>
  Верхний слой. Воду отсюда не берут никогда — сюда попадает всё, что есть на
  поверхности.
</p>

<h3>2–12 метров: суглинок и глина</h3>
<p>
  Водоупор. Он не даёт воде уходить вниз, и он же защищает нижние горизонты от
  того, что течёт сверху. Чем он толще, тем чище вода ниже.
</p>

<h3>12–22 метра: верховодка</h3>
<p>
  Первая вода, до которой можно дойти. Это колодезный горизонт. Он питается
  осадками, поэтому летом проседает, а весной поднимается — и вместе с талой
  водой в него приходят стоки, удобрения и всё с соседних участков. Для питья
  мы этот горизонт не обсаживаем.
</p>

<h3>22–45 метров: водоносный песок</h3>
<p>
  Основной рабочий горизонт для частного дома. Дебит около кубометра в час,
  вода уже под глиняной защитой. Нужен фильтр из нержавейки, подобранный под
  фракцию песка. Срок службы 5–15 лет. Это то, что называют
  <a href="<?= e(u('/uslugi/na-pesok/')) ?>">скважиной на песок</a>.
</p>

<h3>45–70 метров: плотная глина</h3>
<p>
  Второй водоупор. Проходится насквозь, если идём глубже.
</p>

<h3>Глубже 70 метров: известняк</h3>
<p>
  Артезианский горизонт. Вода идёт из трещин в породе, защищена сверху двумя
  водоупорами, не зависит ни от засухи, ни от соседей. Дебит стабильный, срок
  службы — десятилетия. Это
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">артезианская скважина</a>.
</p>

<h2>Почему у соседа 30 метров, а вам называют 60</h2>
<p>
  Потому что слои не лежат ровными плитами. Они изгибаются, выклиниваются,
  прерываются. В Донбассе к естественной геологии добавляется ещё и наследие
  горных выработок: там, где велась добыча, картина может отличаться от
  соседней улицы кардинально. Поэтому любая цифра по телефону — это оценка, а
  не обещание.
</p>

<h2>Как понять, на какую глубину идти вам</h2>
<ul>
  <li><b>Спросите соседей.</b> Глубина их скважин — самый точный доступный
      ориентир. Спрашивайте не «сколько метров», а «сколько метров и как давно,
      и не просаживается ли летом».</li>
  <li><b>Оцените потребление.</b> Дом на семью и полив — хватит песка. Теплицы,
      скотина, несколько домов — считайте известняк.</li>
  <li><b>Подумайте о горизонте планирования.</b> Скважина на песок через 10 лет
      может потребовать замены. Если дом строится «навсегда» — разница в цене
      окупается.</li>
  <li><b>Вызовите инженера.</b> Это бесплатно и ни к чему не обязывает.</li>
</ul>

<h2>Чего точно не стоит делать</h2>
<p>
  Не стоит соглашаться на «пробурим на сколько получится, а там посмотрим».
  Глубина и горизонт должны быть названы до начала работ, вместе с тем, что
  будет, если фактическая глубина окажется больше. Иначе разговор о деньгах
  начнётся, когда установка уже стоит на участке, а торговаться в этот момент
  неудобно.
</p>
