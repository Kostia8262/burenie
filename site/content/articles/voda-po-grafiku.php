<p>
  Подача по графику меняет быт сильнее, чем кажется со стороны. День
  выстраивается вокруг часов подачи: набрать, постирать, помыться, наполнить
  ёмкости. Бельё ждёт воду, а не наоборот. Вопрос, который люди задают нам чаще
  всего, звучит так: скважина действительно снимает эту зависимость или просто
  добавляет ещё один источник к бочкам и подвозу?
</p>
<p>
  Отвечаем честно и по частям, потому что «да» здесь с оговорками.
</p>

<h2>Чем скважина отличается от накопителя</h2>
<p>
  Ёмкость, в которую набирают воду в часы подачи, решает задачу наполовину: она
  сглаживает график, но не делает вас независимым. Кончилась вода в баке — вы
  снова ждёте расписание. Объём упирается в место: бак на тонну занимает угол
  двора, а семье из четырёх человек этого хватает примерно на два дня обычного
  расхода.
</p>
<p>
  Скважина устроена иначе. Вода поступает из горизонта под участком, и сколько
  её брать — решаете вы, а не расписание. Накопитель при этом чаще всего
  остаётся в системе, но выполняет другую работу: держит давление и позволяет
  пережить отключение света, а не заменяет собой водопровод.
</p>

<h2>Сколько воды нужно дому</h2>
<p>
  Ориентир для расчёта — 150–200 литров на человека в сутки при обычном укладе:
  душ, кухня, стиральная машина, санузел. Семья из четырёх человек — это
  примерно 600–800 литров в день, и это без полива. Огород и теплица добавляют
  столько же, а то и больше, причём именно в те недели, когда воды не хватает
  всем сразу.
</p>
<p>
  Песчаный горизонт такие объёмы обычно закрывает: его хватает на дом с
  несколькими точками разбора и на полив. Если расход выше — большой участок,
  две семьи в одном доме, теплицы — разговор идёт про
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">известняковый горизонт</a>,
  который не зависит ни от засухи, ни от того, сколько качают соседи. Разницу
  между горизонтами мы разобрали в статье
  <a href="<?= e(u('/stati/pesok-ili-izvestnyak/')) ?>">песок или известняк</a>.
</p>

<h2>А если отключат свет</h2>
<p>
  Это главный практический вопрос, и обходить его нечестно. Скважинный насос
  работает от электричества: нет света — нет воды из скважины. Поэтому в наших
  краях скважину имеет смысл сразу планировать вместе с запасом.
</p>
<p>
  Рабочих вариантов два, и они не исключают друг друга. Первый — накопительная
  ёмкость в доме или на чердаке: насос наполняет её, когда свет есть, а
  расходуется она самотёком или через небольшой насос. Второй — генератор или
  аккумулятор: скважинному насосу для дома обычно достаточно небольшой
  мощности, и на время отключения его хватает. Гидроаккумулятор, который стоит
  в любой системе, сам по себе даёт только несколько десятков литров — это
  запас на посуду и руки, но не на день жизни.
</p>
<p>
  Практический вывод: скважина снимает зависимость от графика подачи, но не от
  электричества. Зависимость от света снимается отдельно и стоит недорого по
  сравнению с самой скважиной.
</p>

<h2>Что с качеством воды</h2>
<p>
  Вода из скважины не проходит городскую подготовку, и это не всегда минус.
  В неё не попадает то, что набирается в старых сетях, но появляются свои
  особенности горизонта: жёсткость и железо в Донбассе — обычное дело. Решается
  это подбором фильтра после
