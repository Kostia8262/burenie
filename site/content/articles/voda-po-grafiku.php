</p>
<p>
  Важная оговорка про верховодку. Первый водоносный слой на 8–15 метрах кажется
  дешёвым решением, но в него попадает всё с поверхности — стоки, удобрения,
  содержимое соседских септиков. Пить такую воду нельзя, даже если она
  прозрачная. Рабочие горизонты лежат ниже водоупора.
</p>

<h2>Сколько времени занимает переход</h2>
<p>
  Само бурение — один-два дня. Ещё день уходит на обустройство: оголовок,
  насос, автоматика, ввод трубы в дом. То есть от звонка до воды в кране
  проходит обычно неделя с учётом выезда и согласования даты. Зимой сроки те
  же: <a href="<?= e(u('/uslugi/zimoy/')) ?>">бурить можно круглый год</a>,
  мёрзлый грунт мешает технике меньше, чем раскисший.
</p>

<h2>Что делать, если не готовы бурить сейчас</h2>
<p>
  Скажем прямо: если денег на скважину сейчас нет, ёмкость под подачу — нормальное
  временное решение, и мы не будем убеждать вас в обратном. Но если вы уже
  считаете, во сколько обходится подвоз и сколько времени уходит на «поймать
  подачу», посчитайте и скважину: она окупается не за месяц, но перестаёт
  тратить ваше время сразу.
</p>
