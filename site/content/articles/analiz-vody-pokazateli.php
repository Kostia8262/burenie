<p>
  Протокол анализа воды выглядит как таблица из двадцати строк с латинскими
  обозначениями. На практике смотреть нужно на несколько ключевых показателей —
  они определяют и безопасность воды, и то, какая понадобится
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистка</a>.
</p>

<h2>Железо</h2>
<p>
  Самая частая проблема региона. Из крана идёт прозрачная вода, но, постояв
  полчаса, желтеет и даёт рыжий осадок. На сантехнике подтёки, бельё сереет.
  Железо бывает в разных формах — растворённое, окисленное, органическое, — и
  метод очистки зависит именно от формы, а не только от количества.
</p>

<h2>Жёсткость</h2>
<p>
  Соли кальция и магния. Накипь в чайнике и бойлере, перерасход моющих, плёнка
  на чае, сухая кожа после душа. Для артезианских скважин на известняк высокая
  жёсткость — почти правило. Лечится умягчителем на ионообменной смоле.
</p>

<h2>Сероводород</h2>
<p>
  Узнаётся по запаху тухлых яиц. Характерен для глубоких горизонтов. Опасен не
  столько для здоровья, сколько для оборудования — вызывает коррозию. Убирается
  аэрацией и угольным фильтром.
</p>

<h2>Нитраты и нитриты</h2>
<p>
  Маркер того, что в воду попадает поверхностный сток: удобрения с огородов,
  содержимое септиков, стоки с ферм. Для взрослых опасность умеренная, для
  грудных детей нитраты критичны. Высокие нитраты — почти всегда признак
  <a href="<?= e(u('/stati/na-kakuyu-glubinu-burit/')) ?>">верховодки</a>, и
  правильное решение здесь не фильтр, а более глубокая скважина.
</p>

<h2>Мутность и взвешенные вещества</h2>
<p>
  Если скважина сдана и прокачана, а мутность высокая — скорее всего, проблема
  с фильтром или скважина
  <a href="<?= e(u('/stati/skvazhina-zailila/')) ?>">заиливается</a>. Здесь
  сначала чинят скважину, потом думают о фильтрах.
</p>

<h2>Марганец</h2>
<p>
  Часто идёт вместе с железом. Даёт чёрный налёт на сантехнике и тёмный осадок.
  Убирается тем же обезжелезиванием, но требует внимательного подбора засыпки.
</p>

<h2>Микробиология</h2>
<p>
  Отдельный анализ, который заказывают вместе с химическим. Для скважин на
  неглубокие горизонты и для колодцев он обязателен: химия может быть идеальной,
  а вода при этом небезопасна.
</p>

<h2>Как сдавать пробу</h2>
<ul>
  <li>тара — чистая, лучше из лаборатории, не из-под сладких напитков;</li>
  <li>перед отбором слить воду 10–15 минут;</li>
  <li>набирать под горлышко, без воздушного пузыря;</li>
  <li>довезти в лабораторию в течение нескольких часов, в прохладе;</li>
  <li>для микробиологии — только стерильная тара от лаборатории.</li>
</ul>
<p>
  Нарушите правила отбора — получите анализ своей бутылки, а не своей скважины.
  Мы <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">отбираем и везём пробу сами</a>.
</p>

<h2>Когда сдавать</h2>
<ul>
  <li>сразу после бурения и прокачки;</li>
  <li>раз в год-два для работающей скважины;</li>
  <li>при любом изменении вкуса, запаха или цвета;</li>
  <li>перед покупкой системы водоочистки;</li>
  <li>если по соседству появился септик, ферма или поля.</li>
</ul>

<h2>Главное</h2>
<p>
  Не покупайте фильтры до анализа. Универсального набора «на любую воду» не
  существует: система против жёсткости и система против железа — это разные
  деньги и разное железо в котельной.
</p>
