<p>
  В Мангуш выезжаем из Донецка, по пути на побережье. Работаем и в самом
  посёлке, и в окрестных сёлах: частные дома, хозяйства, дачные участки.
  Осмотр участка и расчёт бесплатные.
</p>

<h2>Что учитываем</h2>
<p>
  Мангуш стоит в степной зоне недалеко от моря, и это сочетание даёт две
  особенности. Первая — засушливое лето: верхний горизонт питается осадками, и
  в июле его может не хватать. Вторая — близость побережья, где верхняя вода
  местами минерализована. Обе проблемы решаются одинаково: не брать первую
  воду, а идти на горизонт ниже водоупора. Чем они отличаются, разобрано в
  статье <a href="<?= e(u('/stati/pesok-ili-izvestnyak/')) ?>">песок или
  известняк</a>.
</p>

<h2>Огород и полив</h2>
<p>
  Здесь почти всегда считают воду не только на дом. Полив — самая тяжёлая
  нагрузка, и он приходится на те же недели, когда воды не хватает всем. Если
  у вас теплицы или большой огород, скажите об этом на осмотре: от этого
  зависит и диаметр обсадной колонны, и
  <a href="<?= e(u('/uslugi/nasos/')) ?>">насос</a>, и есть ли смысл в
  накопительной ёмкости.
</p>
<p>
  Прикинуть порядок суммы за проходку можно в
  <a href="<?= e(u('/kalkulyator/')) ?>">калькуляторе</a>, но итог назовём
  после выезда — он бесплатный и ни к чему не обязывает.
</p>
