<h2>Что учитываем в Мариуполе</h2>
<p>
  Приазовье геологически не похоже на остальной Донбасс: кристаллические
  породы здесь подходят к поверхности ближе, а близость моря местами делает
  воду верхних горизонтов минерализованной и солоноватой. Поэтому по
  Мариуполю мы особенно не любим называть глубину по телефону — разброс между
  участками больше, чем где-либо ещё в республике, и честный ответ даёт только
  выезд и разрез соседних скважин.
</p>
