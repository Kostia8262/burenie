<h2>Вода рядом с водохранилищем — не то же самое, что вода из-под крана</h2>
<p>
  Близость большой воды сбивает с толку: кажется, что копать нужно неглубоко.
  На деле верхний горизонт у водохранилища связан с поверхностью напрямую, в
  него попадает всё, что смывается с берегов и огородов. Такая вода бывает
  прозрачной и при этом не проходит по микробиологии. Для дома мы берём
  горизонт ниже водоупора, а верхнюю воду оставляем в стороне —
  <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ</a> после пуска
  показывает разницу наглядно.
</p>

<h2>Дачные участки</h2>
<p>
  На дачах чаще просят летний вариант: вода нужна с весны по осень, зимой дом
  пустует. Это рабочее решение и оно дешевле, главное — честно понимать, что
  на зиму систему придётся консервировать. Если планируете со временем жить
  круглый год, разумнее сразу заложить
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a>: переделывать
  обустройство потом дороже, чем сделать сразу.
</p>
