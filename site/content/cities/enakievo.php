<p>
  В Енакиево выезжаем из Донецка вместе с установкой на прицепе: дорога на
  цену не влияет, осмотр участка и смета бесплатные. Бурим в самом городе, в
  Юнокоммунаровске и в посёлках вокруг — там, где частный дом, огород и
  теплица, а центральной воды либо нет, либо она идёт по графику.
</p>

<h2>Что смотрим на участке</h2>
<p>
  Енакиево — старый промышленный и шахтёрский город, и это главное, что
  определяет конструкцию скважины. Рядом с отвалами и подработанными участками
  верхние воды часто непригодны: их мы отсекаем обсадной колонной и идём на
  рабочий горизонт. Какой именно —
  <a href="<?= e(u('/uslugi/na-pesok/')) ?>">песок</a> или
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">известняк</a> — решаем после
  выезда и разговора о соседских скважинах.
</p>

<h2>Сроки и обустройство</h2>
<p>
  На саму скважину уходит один–два дня, вода из устья идёт в тот же день.
  Дальше — прокачка до чистой воды, насос, автоматика и ввод в дом. Если
  бюджет нужно растянуть, начинаем с
  <a href="<?= e(u('/uslugi/letnee/')) ?>">летнего обустройства</a> для полива,
  а зимний вариант с <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптером</a>
  добавляем позже — скважину под это мы сразу делаем с запасом.
</p>
