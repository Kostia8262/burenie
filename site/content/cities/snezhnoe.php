<p>
  Снежное — самый дальний от нас восток, дорога из Донецка занимает около
  полутора часов. Это не мешает: установка едет на прицепе и отдельной
  логистики не требует, а выезд инженера всё равно бесплатный. Бурим в частном
  секторе города и в посёлках вокруг.
</p>

<h2>Что учитываем в Снежном</h2>
<p>
  Город стоит высоко, на Донецком кряже, и рельеф здесь работает против
  неглубокой воды: отметки выше, чем в низинах вокруг, поэтому верхний
  горизонт бывает бедным и пересыхающим к августу. Если сосед жалуется, что
  колодец летом уходит, это как раз тот случай — надёжнее сразу считать
  скважину <a href="<?= e(u('/uslugi/na-pesok/')) ?>">на песок</a>, а при
  слабом горизонте — <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">на
  известняк</a>.
</p>
<p>
  Вокруг те же подработанные шахтные поля, что и по всему востоку республики,
  так что воду из верховодки под питьё мы не берём. Фактическую глубину,
  конструкцию и замеренный дебит записываем в паспорт скважины — не «примерно
  как у соседей», а то, что получилось на вашем участке.
</p>

<h2>Как проходит работа</h2>
<p>
  Один–два дня на скважину, вода из устья в тот же день. Дальше
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a> или
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a>, насос, ввод в дом — либо
  <a href="<?= e(u('/uslugi/letnee/')) ?>">летний вариант</a>, если зимний
  водопровод пока не нужен.
</p>
