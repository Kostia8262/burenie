<p>
  В Горловку выезжаем из Донецка: бригада и малогабаритная установка едут на
  прицепе, отдельной логистики это не требует, наценки за дорогу нет. Бурим в
  Центрально-Городском, Никитовском и Калининском районах, в частном секторе и
  в посёлках вокруг города.
</p>

<h2>Горловская специфика</h2>
<p>
  Горловка — город с сильно изрезанным рельефом и давней горной историей.
  Перепады высот означают, что глубина до воды на соседних улицах может
  отличаться заметно, а подработанные территории — что верхний горизонт стоит
  проверять особенно внимательно. Мы разбираем разрез на участке, смотрим
  соседские скважины и только потом называем глубину и смету.
</p>
<p>
  Второй частый вопрос — перебои с центральной подачей. Скважина эту задачу
  закрывает целиком: с
  <a href="<?= e(u('/uslugi/nasos/')) ?>">насосом и автоматикой</a> вода в доме
  есть независимо от графика, а на случай отключений электричества мы заранее
  обсуждаем ввод от генератора.
</p>

<h2>Что получите на выходе</h2>
<p>
  Обсаженный ствол, прокачку до чистой воды, замеренный дебит, паспорт скважины
  и гарантию на работы. Обустройство —
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a> или
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессон</a> — делаем той же бригадой,
  второй раз вызывать никого не нужно.
</p>
