<h2>Восстановление и новая вода</h2>
<p>
  Частый запрос — не первая скважина на участке, а замена того, что перестало
  работать. Иногда старую скважину можно вернуть в строй:
  <a href="<?= e(u('/uslugi/remont/')) ?>">прокачать, поменять насос,
  переобустроить оголовок</a>. Но если обсадная колонна повреждена, чинить
  бессмысленно — честнее пробурить рядом новую. Что именно с вашей, видно на
  осмотре, и этот ответ мы даём до того, как вы заплатите.
</p>
<p>
  Почему скважины заиливаются и что с этим делать, разобрано в статье
  <a href="<?= e(u('/stati/skvazhina-zailila/')) ?>">скважина заилилась</a>.
</p>

