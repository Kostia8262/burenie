<p>
  Седово — курортный посёлок, и запрос здесь особенный: воду чаще заказывают
  не под дом на одну семью, а под базу отдыха, гостевой дом или несколько
  домиков сразу. Выезжаем из Донецка, расчёт бесплатный.
</p>

<h2>Курортная нагрузка</h2>
<p>
  Летом расход воды на базе отдыха скачет в разы: душевые, кухня, стирка,
  полив — и всё это в те же часы, что у соседей. Поэтому для Седово мы сначала
  считаем пиковый расход, а уже потом выбираем горизонт и
  <a href="<?= e(u('/uslugi/nasos/')) ?>">насос</a>. Скважина, которой хватает
  зимой на сторожа и не хватает в июле на двадцать человек, — это деньги,
  потраченные наполовину.
</p>
<p>
  Если объект оформлен на организацию, работу ведём
  <a href="<?= e(u('/uslugi/yurlicam/')) ?>">по договору с документами</a>:
  счёт, акты, паспорт скважины. Вопрос разрешений обсуждаем отдельно — что
  требуется в каком случае, мы разобрали в статье
  <a href="<?= e(u('/stati/nuzhna-li-licenziya/')) ?>">нужна ли лицензия</a>.
</p>

<h2>Про солёную воду</h2>
<p>
  Скажем прямо: на самой косе и у береговой линии верхняя вода бывает
  непригодной для питья из-за минерализации. Мы не обещаем «пресную воду в
  любой точке» — сначала смотрим участок и соседние скважины, и только потом
  говорим, чего ждать. Если картина неблагоприятная, честнее сказать об этом
  до начала работ, а не после.
</p>
