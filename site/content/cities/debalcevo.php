<p>
  В Дебальцево выезжаем из Донецка — дорога занимает часть дня, но на цену это
  не влияет: осмотр участка и расчёт бесплатные. Работаем в частном секторе
  города и в посёлках вокруг, включая дома, которые восстанавливают после
  долгого простоя.
</p>

<h2>Что учитываем в Дебальцево</h2>
<p>
  Город стоит на водоразделе, и с водой здесь исторически непросто: колодцы
  мелкие, летом многие уходят в ноль. Верхний горизонт питается осадками, а
  значит в засуху его не хватает как раз тогда, когда вода нужнее всего.
  Поэтому в Дебальцево мы редко советуем рассчитывать на первую воду и сразу
  обсуждаем <a href="<?= e(u('/uslugi/na-pesok/')) ?>">песчаный горизонт</a>
  или, если расход большой, известняк.
</p>
<p>
  Вторая особенность — застройка. Участки в частном секторе вытянутые и тесные,
  между домом и хозяйственными постройками остаётся немного места. Заезжаем
  <a href="<?= e(u('/uslugi/malogabaritnoe/')) ?>">малогабаритной установкой</a>:
  ей нужен проход от 90 см и площадка около 2×3 метров, забор разбирать не
  придётся.
</p>

<h2>Дома после простоя</h2>
<p>
  Часто просят не пробурить с нуля, а разобраться со старой скважиной: вода
  ушла, насос не качает, оголовок разрушен. Иногда её действительно можно
  вернуть в работу — <a href="<?= e(u('/uslugi/remont/')) ?>">прокачать и
  переобустроить</a> дешевле, чем бурить заново. Но если обсадная колонна
  повреждена, честнее сказать об этом сразу, а не брать деньги за заведомо
  временный результат. Решаем это на осмотре.
</p>
