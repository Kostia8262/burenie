<p>
  Ждановка — небольшой город, и заявок отсюда меньше, чем из Донецка, но ездим
  сюда охотно: участки просторные, работать удобно. Выезд инженера и смета
  бесплатные.
</p>

<h2>Почему в Ждановке спрашивают про скважину</h2>
<p>
  Причина обычно одна: центральная вода идёт не всегда, а держать хозяйство на
  расписании тяжело. Огород, живность, стирка — всё это упирается в часы
  подачи. Скважина эту зависимость снимает, но не снимает зависимость от
  электричества: насос без света не работает. Как это обходят, мы разобрали в
  статье <a href="<?= e(u('/stati/voda-po-grafiku/')) ?>">вода по графику</a> —
  коротко, нужен накопитель или генератор.
</p>

<h2>Горизонты и грунт</h2>
<p>
  Район шахтёрский, поэтому верхнюю воду мы здесь всерьёз не рассматриваем:
  она слишком связана и с поверхностью, и со старыми выработками. Рабочий
  вариант — <a href="<?= e(u('/uslugi/na-pesok/')) ?>">песок</a>, а при большом
  расходе — <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">известняк</a>,
  который не проседает ни в засуху, ни когда соседи качают одновременно.
  Разницу между ними мы разложили в статье
  <a href="<?= e(u('/stati/pesok-ili-izvestnyak/')) ?>">песок или известняк</a>.
</p>
<p>
  Точную глубину называем после осмотра. По телефону честный ответ один:
  в Донбассе песок обычно лежит на 22–45 метрах, но ваш участок может
  оказаться исключением.
</p>
