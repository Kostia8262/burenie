  Докучаевск — юг, чуть больше получаса от нашей базы в Донецке. Бурим в
  частном секторе города и в сёлах вокруг: Еленовка, Стыла, Ольгинка.
</p>

<h2>Что учитываем в Докучаевске</h2>
<p>
  Город живёт флюсо-доломитным комбинатом, и карьеры под боком — это не
  случайность: известняк здесь подходит близко к поверхности. Для скважины это
  скорее хорошая новость, потому что
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">артезианский горизонт</a> с
  его стабильным дебитом может оказаться доступнее, чем в среднем по
  республике. Но «может» — это не обещание: конкретную глубину показывает
  только выезд и разрез соседних скважин.
</p>
<p>
  Обратная сторона известняка — жёсткость. Вода из такой скважины часто
  оставляет накипь, поэтому после бурения имеет смысл сделать
  <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ воды</a> и подобрать
  умягчение в составе
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистки</a>.
</p>

<h2>Как проходит работа</h2>
<p>
  Установка заходит в калитку от 90 см, площадка нужна примерно 2×3 метра,
  забор разбирать не приходится. Один–два дня на скважину, затем обустройство
  и ввод в дом. На выходе — паспорт скважины и гарантия на работы.
</p>
