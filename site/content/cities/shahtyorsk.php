<p>
  В Шахтёрск выезжаем из Донецка — около часа дороги. Работаем в частном
  секторе города и в посёлках вокруг: Контарное, Стожковское, Софиевка.
  По пути закрываем и соседние
  <a href="<?= e(u('/geografiya/torez/')) ?>">Торез</a> со
  <a href="<?= e(u('/geografiya/snezhnoe/')) ?>">Снежным</a>, так что день
  выезда обычно получается согласовать быстро.
</p>

<h2>Что учитываем в Шахтёрске</h2>
<p>
  Название города говорит само за себя: вокруг подработанные территории,
  отвалы и старые шахтные поля. Верхний горизонт в таких местах мы оцениваем
  осторожно и воду из верховодки под питьё не обсаживаем — привкус и запах
  здесь не редкость. Разумный вариант обычно начинается со скважины
  <a href="<?= e(u('/uslugi/na-pesok/')) ?>">на песок</a> с нормальным фильтром
  из нержавейки, а там, где нужен стабильный дебит, —
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">на известняк</a>.
</p>

<h2>Вода и фильтры</h2>
<p>
  Жёсткость и железо для местной воды — обычное дело. Порядок действий такой:
  сначала <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ воды</a> из уже
  готовой скважины, потом подбор
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистки</a> под ваш
  протокол. Одинаковый набор фильтров всем подряд мы не продаём.
</p>

<h2>Как заказать выезд</h2>
<p>
  Позвоните или оставьте номер в форме — согласуем день, инженер приедет,
  посмотрит участок и посчитает смету бесплатно.
</p>
