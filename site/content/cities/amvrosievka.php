<h2>Что учитываем в Амвросиевке</h2>
<p>
  Район известен цементным сырьём — мергелем и известняком, — и карбонатные
  породы здесь лежат неглубоко. На практике это означает две вещи. Первая:
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">артезианская скважина</a>
  часто оказывается реальным вариантом, а не «когда-нибудь потом». Вторая:
  проходка по плотной породе идёт медленнее, чем по песку и глине, и это
  честно отражается в смете: <a href="<?= e(u('/ceny/')) ?>">от <?= e(number_format(PRICE_DRILL_FROM, 0, ',', ' ')) ?> ₽ за метр</a> —
  это обычный грунт, по известняку выйдет дороже. Точную сумму называем
  после выезда.
</p>
<p>
  Вода из карбонатного горизонта обычно жёсткая. Порядок тот же, что везде:
  сначала <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ</a> готовой
  скважины, потом подбор
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">фильтров</a> под протокол.
</p>

<h2>Как заказать выезд</h2>
<p>
  Позвоните или оставьте номер в форме. Инженер приедет, посмотрит подъезд,
  место под установку и точку ввода в дом, спросит про скважины у соседей — и
  назовёт реальную глубину и сумму. Выезд и расчёт бесплатные.
</p>
