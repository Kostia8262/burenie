<h2>Что учитываем в Торезе</h2>
<p>
  Это глубоко шахтёрский район с подработанными территориями и отвалами, и
  верхний горизонт здесь мы оцениваем особенно осторожно: воду из верховодки
  под питьё не берём. Рабочий горизонт определяем на участке — по разрезу,
  рельефу и скважинам у соседей; в паспорт потом идут фактическая глубина,
  конструкция и замеренный дебит, а не «примерно как у всех».
</p>

