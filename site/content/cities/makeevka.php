<p>
  Макеевка для нас — соседний город: от базы в Донецке дорога занимает минут
  двадцать, поэтому выезд инженера здесь такой же бесплатный, как по Донецку.
  Работаем в Центрально-Городском, Кировском, Советском, Червоногвардейском и
  Горняцком районах, а также в посёлках вокруг — Ханженково, Ясиновка,
  Криничная, Новый Свет.
</p>

<h2>Что учитываем в Макеевке</h2>
<p>
  Город вытянут и состоит скорее из посёлков, чем из сплошной застройки: на
  одной улице соседи берут воду с тридцати метров, а через квартал приходится
  идти глубже. Поэтому перед выездом мы всегда спрашиваем про скважины и
  колодцы у соседей — это самая точная геология, которая бывает.
</p>
<p>
  Макеевка стоит на старых шахтных полях. Рядом с отработанными участками
  верхний горизонт бывает с запахом и привкусом, поэтому воду из верховодки мы
  не обсаживаем под питьё — при таком раскладе разумнее скважина
  <a href="<?= e(u('/uslugi/na-pesok/')) ?>">на песок</a> с нормальным фильтром
  или артезианская.
</p>

<h2>Как проходит работа</h2>
<p>
  Установка едет на прицепе и заходит в обычную калитку, вода из устья идёт в
  тот же день. Обустроить скважину можно сразу —
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптером</a> или
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессоном</a>, — либо оставить
  <a href="<?= e(u('/uslugi/letnee/')) ?>">летний вариант</a> и достроить
  зимний позже.
</p>
