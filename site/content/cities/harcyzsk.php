<h2>Почему здесь чаще заказывают скважину</h2>
<p>
  В районе много домов, где центральной воды либо нет, либо давления хватает
  не на все точки. Собственная скважина снимает вопрос целиком: с
  <a href="<?= e(u('/uslugi/nasos/')) ?>">правильно подобранным насосом</a>
  напор в доме не зависит ни от графика, ни от соседей, открывших полив.
</p>
<p>
  Подобрать насос «помощнее на всякий случай» здесь плохая идея: если он
  выбирает воду быстрее, чем скважина её отдаёт, начинается сухой ход и
  выгоревшая обмотка. Поэтому мы считаем насос по замеренному дебиту и глубине,
  а не по каталогу.
</p>

<h2>Как проходит выезд</h2>
<p>
  Инженер смотрит подъезд для установки, место под бурение и точку ввода в дом,
  расспрашивает про скважины у соседей и считает смету на месте. Выезд и расчёт
  бесплатные, от сметы вы ничем не связаны. Дальше — бурение, обсадка,
  прокачка, обустройство и паспорт скважины.
</p>
