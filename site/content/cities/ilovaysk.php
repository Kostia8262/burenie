<p>
  Иловайск недалеко от Донецка, поэтому на осмотр приезжаем обычно в ближайшие
  дни и без наценки за дорогу. Бурим в самом городе и в частном секторе вокруг
  железнодорожного узла, а также в посёлках Харцызского направления.
</p>

<h2>Чем интересен Иловайск</h2>
<p>
  Город вырос вокруг станции, и застройка здесь в основном одноэтажная, с
  большими огородами. Это меняет расчёт: воду берут не только на дом, но и на
  полив, а полив в засушливое лето съедает больше, чем весь бытовой расход.
  Поэтому в Иловайске мы всегда спрашиваем про огород и теплицы — от этого
  зависит и горизонт, и <a href="<?= e(u('/uslugi/nasos/')) ?>">насос</a>.
</p>
<p>
  Рядом с насыпями и путями встречаются насыпные грунты: верхний слой там
  рыхлый и держит поверхностную воду, пить которую нельзя. Разрез разбираем на
  месте и, если верховодка непригодна, уходим ниже — как это устроено, мы
  разобрали в статье
  <a href="<?= e(u('/stati/na-kakuyu-glubinu-burit/')) ?>">на какую глубину бурить</a>.
</p>

<h2>Как проходит работа</h2>
<p>
  Бурение занимает день-два, ещё день — обустройство: оголовок, насос,
  автоматика, ввод в дом. Летний вариант обходится дешевле, но на зиму его
  нужно консервировать; <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптер</a>
  или кессон дороже, зато скважина работает круглый год. Что выбрать, зависит
  от того, живёте вы в доме постоянно или приезжаете на сезон.
</p>
