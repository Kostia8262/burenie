<h2>Сколько воды считать</h2>
<p>
  Ошибка, которую мы чаще всего видим в частных хозяйствах, — считать расход
  только по людям. Семья из четырёх человек — это 600–800 литров в сутки, но
  живность, летний полив и теплица легко удваивают цифру. Скважина, рассчитанная
  «на дом», в июле начинает не справляться. Поэтому на осмотре мы спрашиваем
  про хозяйство подробно, и от ответа зависит горизонт.
</p>

