<h2>Чем сложен частный сектор Донецка</h2>
<p>
  Дворы тесные, въезд часто шириной в калитку, а между домом, гаражом и
  теплицей остаётся пара метров. Крупная установка сюда не заходит, поэтому
  мы работаем
  <a href="<?= e(u('/uslugi/malogabaritnoe/')) ?>">малогабаритной установкой</a>:
  ей нужен проход от 90 см и площадка примерно 2×3 метра. Забор разбирать не
  приходится, колеи через весь участок после нас не остаётся.
</p>
<p>
  Вторая особенность города — старые горные выработки и насыпные грунты рядом
  с терриконами. На таких участках верхний горизонт часто отравлен шахтной
  водой, и брать воду из него нельзя: разрез мы разбираем на месте и, если
  верховодка непригодна, идём ниже — на песок или на
  <a href="<?= e(u('/uslugi/na-izvestnyak/')) ?>">известняк</a>.
</p>

<h2>Вода в Донецке: что обычно встречаем</h2>
<p>
  По городу чаще всего работает песчаный горизонт — его хватает на дом с
  несколькими точками разбора и полив. Жёсткость и железо в донецкой воде —
  обычное дело, поэтому после пуска скважины имеет смысл сдать
  <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ воды</a> и подбирать
  фильтры уже по протоколу, а не наугад.
</p>
