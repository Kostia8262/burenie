<h2>Вода рядом с водохранилищем</h2>
<p>
  Большая вода поблизости не означает, что хорошая вода лежит неглубоко.
  Верхний горизонт у водоёма связан с поверхностью напрямую: в него попадает
  сток с полей и огородов. Для питья мы такую воду не берём и идём ниже
  водоупора — на <a href="<?= e(u('/uslugi/na-pesok/')) ?>">песчаный
  горизонт</a>, а при большом расходе глубже.
</p>
<p>
  Чем отличаются горизонты и почему разница не только в глубине, разобрано в
  статье <a href="<?= e(u('/stati/pesok-ili-izvestnyak/')) ?>">песок или
  известняк</a>.
</p>

<h2>Как проходит работа</h2>
<p>
  Бурение — день-два, обустройство — ещё день. На выходе паспорт скважины с
  глубиной, разрезом и замеренным дебитом: это документ, по которому потом
  видно, что именно вам сделали. Как принимать работу и что проверять, мы
  расписали в статье
  <a href="<?= e(u('/stati/kak-prinyat-skvazhinu/')) ?>">как принять скважину</a>.
</p>
