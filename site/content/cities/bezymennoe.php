<h2>Чего ждать от горизонтов</h2>
<p>
  Как и по всему побережью, верхняя вода тут может быть солоноватой, а летом
  ещё и проседать: колодцы мелеют как раз в разгар полива. Поэтому в
  Безыменном мы сразу считаем, сколько воды нужно в пик, и от этого выбираем
  горизонт. Если расход большой — огород плюс живность — разговор идёт про
  горизонт поглубже, который не зависит от того, сколько выпало дождей.
</p>
<p>
  Что именно у вас под участком, показывает первая же проходка. До неё честный
  ответ — «увидим на месте»; любые точные цифры по телефону в приморской
  полосе означают, что их назвали наугад.
</p>

