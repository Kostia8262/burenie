  Селидово и посёлки вокруг — шахтёрский район с большим частным сектором.
  Выезжаем из Донецка, осмотр участка и расчёт бесплатные.
</p>

<h2>Верхняя вода здесь не вариант</h2>
<p>
  Под городом и вокруг него — старые горные работы, и первый водоносный слой
  часто подпитан шахтной водой. Внешне она может быть чистой, а по анализу
  давать железо и сульфаты. Поэтому в Селидово мы проходим верховодку
  насквозь: скважина, из которой нельзя пить, не стоит своих денег, даже если
  обошлась дёшево.
</p>
<p>
  Если у соседей есть скважина, скажите её глубину — по ней картина
  проясняется ещё до выезда. В пределах улицы разрез обычно повторяется.
</p>

<h2>Что делаем</h2>
<p>
  Полный цикл: бурение, обсадная колонна, фильтр, прокачка до чистой воды,
  <a href="<?= e(u('/uslugi/nasos/')) ?>">насос</a> с автоматикой и ввод в дом.
  На выходе паспорт скважины. Если вода после пуска окажется жёсткой или
  железистой, подбираем
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистку</a> по анализу, а
  не наугад.
</p>
