<p>
  Моспино близко к Донецку — по сути городская окраина, поэтому выезжаем
  быстро и без наценки за дорогу. Работаем в частном секторе и на дачных
  участках вокруг.
</p>

<h2>Чем удобно работать в Моспино</h2>
<p>
  Застройка частная, участки с огородами, подъезд к большинству дворов
  нормальный. Там, где ворота узкие или двор занят постройками, заходим
  <a href="<?= e(u('/uslugi/malogabaritnoe/')) ?>">малогабаритной установкой</a>:
  ей хватает прохода от 90 см. Газон и грядки после работы остаются целыми —
  это не рекламная фраза, а следствие того, что тяжёлой технике здесь заезжать
  некуда.
</p>

<h2>Вода</h2>
<p>
  Окрестности Моспино — старый угольный район, и к верхнему горизонту мы здесь
  относимся с осторожностью: он может быть подпитан шахтной водой. Смотрим
  разрез на месте и, если первая вода непригодна, идём ниже. Это не удорожание
  ради удорожания: скважина, из которой нельзя пить, не стоит потраченных
  денег.
</p>
<p>
  После пуска имеет смысл сдать
  <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ воды</a> и уже по
  результату решать, нужна ли
  <a href="<?= e(u('/uslugi/vodoochistka/')) ?>">водоочистка</a>. Подбирать
  фильтры наугад — самый дорогой способ.
</p>
