<p>
  Старобешево — юг республики, около сорока минут от Донецка. Бурим в самом
  посёлке и в сёлах вокруг: Новый Свет, Осыково, Раздольное.
</p>

<h2>Что учитываем в Старобешево</h2>
<p>
  Посёлок стоит на Кальмиусе, и участки у воды ведут себя иначе, чем участки
  на возвышенности: в пойме верхний горизонт ближе, но именно там выше риск
  поймать верховодку с поверхностным загрязнением. Под питьё такую воду мы не
  обсаживаем — идём глубже, на нормальный горизонт
  <a href="<?= e(u('/uslugi/na-pesok/')) ?>">на песок</a> с фильтром из
  нержавейки.
</p>
<p>
  Вокруг много дачных и садовых массивов, где нужен не водопровод в дом, а
  вода на полив. Для такого сценария есть
  <a href="<?= e(u('/uslugi/letnee/')) ?>">летнее обустройство</a>: оголовок,
  насос и кран, а зимний вариант можно достроить позже, не переделывая
  скважину. Подробнее — на странице
  <a href="<?= e(u('/uslugi/dacha/')) ?>">скважины на даче</a>.
</p>

<h2>Как проходит работа</h2>
<p>
  Установка едет на прицепе и заходит в обычную калитку. Один–два дня на
  скважину, вода из устья в тот же день, на выходе — паспорт скважины с
  фактической глубиной, конструкцией и замеренным дебитом.
</p>
