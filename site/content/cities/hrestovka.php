<p>
  В Хрестовку приезжаем из Донецка, выезд и расчёт бесплатные. Бурим в частном
  секторе города и в посёлках вокруг — там, где центральной воды либо нет, либо
  она идёт по графику.
</p>

<h2>Шахтёрский город: что это меняет</h2>
<p>
  Хрестовка стоит в районе старых горных работ, и это главное, что мы
  учитываем. Под такими участками грунт бывает нарушен, а верхний водоносный
  слой — подпитан шахтной водой. Внешне она нормальная, по анализу — железо,
  сульфаты, иногда минерализация выше питьевой нормы. Поэтому здесь мы почти
  всегда проходим верховодку насквозь и ставим фильтр на рабочем горизонте, а
  <a href="<?= e(u('/uslugi/analiz-vody/')) ?>">анализ воды</a> после пуска
  советуем делать не для галочки.
</p>
<p>
  Если у соседей есть скважина — скажите её глубину. По ней мы прикинем разрез
  ещё до выезда: в пределах одной улицы картина обычно повторяется, а вот через
  квартал может отличаться вдвое.
</p>

<h2>Что делаем</h2>
<p>
  Полный цикл: бурение, обсадка, фильтр, прокачка до чистой воды, насос и ввод
  в дом. На выходе — паспорт скважины с глубиной, разрезом и замеренным
  дебитом. Зачем он нужен и как принимать работу, мы описали в статье
  <a href="<?= e(u('/stati/kak-prinyat-skvazhinu/')) ?>">как принять скважину</a>.
</p>
