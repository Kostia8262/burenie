<p>
  Ясиноватая от нашей базы в Донецке — полчаса дороги, поэтому выезд инженера
  сюда такой же бесплатный, как по городу. Бурим в частном секторе самой
  Ясиноватой и в посёлках вокруг: Спартак, Васильевка, Верхнеторецкое,
  Крутая Балка.
</p>

<h2>Что учитываем в Ясиноватой</h2>
<p>
  Город вырос вокруг узловой станции, и застройка здесь пёстрая: кварталы
  многоэтажек чередуются с частным сектором и дачными массивами. Для нас это
  значит, что подъезд к участку нужно смотреть заранее — где-то установка
  заходит во двор свободно, где-то приходится заводить её
  <a href="<?= e(u('/uslugi/malogabaritnoe/')) ?>">малогабаритным вариантом</a>
  через калитку.
</p>
<p>
  Глубину называем после выезда. Ориентир по Донбассу прежний: песчаный
  горизонт обычно лежит на 22–45 метрах, известняковый глубже 70, но соседние
  улицы отличаются вдвое. Самая точная геология — скважины у соседей, поэтому
  про них мы спрашиваем в первую очередь.
</p>

<h2>Как проходит работа</h2>
<p>
  Установка едет на прицепе, бригада работает на месте один–два дня, вода из
  устья идёт в тот же день. Дальше либо обустраиваем сразу —
  <a href="<?= e(u('/uslugi/adapter/')) ?>">адаптером</a> или
  <a href="<?= e(u('/uslugi/kesson/')) ?>">кессоном</a>, — либо оставляем
  <a href="<?= e(u('/uslugi/letnee/')) ?>">летний вариант</a> и достраиваем
  зимний позже.
</p>
