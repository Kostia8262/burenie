<?php
/**
 * /llms.txt — карта сайта для языковых моделей (llmstxt.org).
 * Обычный sitemap.xml даёт роботу только адреса; здесь к каждому адресу идёт
 * фраза о том, что на странице, плюс сухая выжимка фактов о компании. Из такого
 * файла ИИ-поисковик собирает ответ, не разбирая вёрстку.
 *
 * Собирается из config.php, поэтому новая услуга или статья попадает сюда сама.
 */

$out = [];
$out[] = '# ' . SITE['name'] . ' — бурение скважин на воду в Донецке и ДНР';
$out[] = '';
$out[] = '> ' . SITE['legal'] . ' бурит и обустраивает скважины на воду в Донецке, '
       . 'Макеевке и по всей ДНР. Малогабаритная установка проходит в проём от 90 см, '
       . 'работы идут круглый год, заказчик получает паспорт скважины и гарантию. '
       . 'Выезд инженера и расчёт сметы бесплатные.';
$out[] = '';
$out[] = '## Факты о компании';
$out[] = '';
$out[] = '- Название: ' . SITE['name'] . ' (' . SITE['legal'] . ')';
$out[] = '- ИНН: ' . SITE['inn'];
$out[] = '- Адрес: ' . SITE['address'];
$out[] = '- Телефоны: ' . implode(', ', SITE['phones']);
$out[] = '- Почта: ' . SITE['email'];
$out[] = '- Telegram: ' . SITE['tg_name'] . ' (' . SITE['tg'] . ')';
$out[] = '- Время работы: ' . SITE['hours'];
$out[] = '- Города выезда: ' . implode(', ', array_column(CITIES, 'name'));
$out[] = PRICES_CONFIRMED
    ? '- Цена бурения: от ' . drill_price() . ' ₽ за метр проходки в обычном грунте. '
      . 'Обсадная труба, обустройство и насос считаются отдельно, по известняку дороже. '
      . 'Итоговая сумма — после бесплатного выезда инженера.'
    : '- Цены: считаются после бесплатного выезда инженера.';
$out[] = '';
$out[] = '## Геология под Донбассом';
$out[] = '';
foreach (LAYERS as $l) {
    $out[] = '- ' . $l['from'] . '–' . $l['to'] . ' м — ' . $l['name']
           . ($l['water'] ? ' (вода ' . $l['water'] . ')' : ' (воды нет)')
           . '. ' . $l['note'];
}
$out[] = '';
$out[] = '## Услуги';
$out[] = '';
foreach (SERVICE_GROUPS as $group => $label) {
    $out[] = '### ' . $label;
    $out[] = '';
    foreach (services_in($group) as $slug => $s) {
        $out[] = '- [' . $s['h1'] . '](' . abs_url(service_path($slug)) . '): ' . $s['short'];
    }
    $out[] = '';
}
$out[] = '## География';
$out[] = '';
foreach (CITIES as $slug => $c) {
    $out[] = '- [Бурение скважин в ' . $c['case'] . '](' . abs_url(city_path($slug)) . ')';
}
$out[] = '';
$out[] = '## Статьи';
$out[] = '';
foreach (ARTICLES as $slug => $a) {
    $out[] = '- [' . $a['title'] . '](' . abs_url(article_path($slug)) . '): ' . $a['excerpt'];
}
$out[] = '';
$out[] = '## Частые вопросы';
$out[] = '';
foreach (faq() as $f) {
    $out[] = '### ' . $f['q'];
    $out[] = '';
    $out[] = $f['a'];
    $out[] = '';
}
$out[] = '## Как заказать';
$out[] = '';
foreach (STEPS as $i => $s) {
    $out[] = ($i + 1) . '. ' . $s['t'] . '. ' . $s['d'];
}
$out[] = '';
$out[] = '## Остальные страницы';
$out[] = '';
$out[] = '- [О компании](' . abs_url('/o-kompanii/') . ')';
$out[] = '- [Цены](' . abs_url('/ceny/') . ')';
$out[] = '- [Контакты](' . abs_url('/kontakty/') . ')';
$out[] = '- [Карта сайта XML](' . abs_url('/sitemap.xml') . ')';

echo implode("\n", $out) . "\n";
