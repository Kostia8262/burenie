/**
 * Винительный падеж названия города: «выезжаем в Макеевку», «в Мариуполь».
 * В CITIES лежат только именительный и предложный, а предложный в обороте
 * «выезжаем в …» звучит неграмотно («выезжаем в Мариуполе»). Правило простое
 * и на нашем списке городов срабатывает целиком: -ая → -ую, -я → -ю,
 * -а → -у, остальные не меняются.
 */
function city_acc(string $name): string
{
    if (mb_substr($name, -2) === 'ая') {
        return mb_substr($name, 0, -2) . 'ую';
    }
    if (mb_substr($name, -1) === 'я') {
        return mb_substr($name, 0, -1) . 'ю';
    }
    if (mb_substr($name, -1) === 'а') {
        return mb_substr($name, 0, -1) . 'у';
    }
    return $name;
}

