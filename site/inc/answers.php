/**
 * Блок «Коротко» — таблица фактов сразу под заголовком страницы.
 * Класс .answer размечен так, чтобы его можно было отдать в speakable:
 * это первый на странице фрагмент, пригодный на роль прямого ответа.
 */
function facts_block(array $facts, string $title = 'Коротко'): string
{
    if (!$facts) {
        return '';
    }
    $o = '<div class="answer"><h2 class="answer__h">' . e($title) . '</h2><dl class="answer__list">';
    foreach ($facts as [$k, $v]) {
        $o .= '<div class="answer__row"><dt>' . e($k) . '</dt><dd>' . e($v) . '</dd></div>';
    }
    return $o . '</dl></div>';
}

/** Блок вопросов и ответов. Разметку FAQPage отдаём отдельно — faq_schema(). */
function faq_block(array $faq, string $title = 'Частые вопросы'): string
{
    if (!$faq) {
        return '';
    }
    $o = '<section class="sec sec--s1"><div class="wrap">'
       . '<div class="sec-head"><h2 class="d2">' . e($title) . '</h2></div>'
       . '<div class="faq faq--cols">';
    foreach ($faq as $f) {
        $o .= '<details><summary>' . e($f['q']) . '</summary>'
            . '<div class="faq__a"><p>' . e($f['a']) . '</p></div></details>';
    }
    return $o . '</div></div></section>';
}

/** Разметка FAQPage для набора вопросов. */
function faq_schema(array $faq, string $path): array
{
    return [
        '@context'   => 'https://schema.org',
        '@type'      => 'FAQPage',
        '@id'        => abs_url($path) . '#faq',
        'inLanguage' => 'ru-RU',
        'mainEntity' => array_map(fn($f) => [
            '@type'          => 'Question',
            'name'           => $f['q'],
            'acceptedAnswer' => ['@type' => 'Answer', 'text' => $f['a']],
        ], $faq),
    ];
}

/**
 * Довесок к разметке статьи: объём текста, время чтения, рубрика, обложка.
 * Считается по самому файлу статьи, поэтому цифры не расходятся с текстом.
 * Обложка добавляется только если файл есть — ссылка на несуществующую
 * картинку в разметке считается ошибкой и гасит расширенный сниппет.
 */
function article_extras(string $slug, array $art): array
{
    $out = [
        'wordCount'    => article_words($slug),
        'timeRequired' => 'PT' . read_time($slug) . 'M',
    ];
    if (!empty($art['topic'])) {
        $out['articleSection'] = $art['topic'];
    }
    $rel = '/assets/img/illu/art/' . $slug . '.webp';
    if (is_file(__DIR__ . '/..' . $rel)) {
        $out['image'] = abs_url($rel);
    }
    return $out;
}

/** Число слов в статье. Теги и PHP-вставки не считаем. */
function article_words(string $slug): int
{
    $file = __DIR__ . '/../content/articles/' . $slug . '.php';
    if (!is_file($file)) {
        return 0;
    }
    $raw = preg_replace('/<\?.*?\?>/s', ' ', (string) file_get_contents($file));
    return (int) preg_match_all('/[\p{L}\p{N}]+/u', strip_tags((string) $raw));
}
